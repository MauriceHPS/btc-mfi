    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        dialog=new CaretSearchDialog();
        String qry="select identifier, date::date from savings_management where identifier ilike '%{f}%' order by date desc";
        dialog.setSearchQuery(qry);
        AMSUtility.showSearchDialog(jTextField1, dialog);
        Object [] object=dialog.getSelectedValue();
        if(object!=null){
            jTextField1.setText(object[0].toString());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if(buttonGroup1.getSelection()==null){
            JOptionPane.showMessageDialog(this, "Kindly select a radio button above");
            return;
        }
        //By ID
        if(jRadioButton1.isSelected()){
            if(jTextField1.getText().isEmpty()){
                JOptionPane.showMessageDialog(this, "Kindly select the savings no");
                return;
            }
            SavingsByIDPdf s=new SavingsByIDPdf();
            s.SavingsByIDPdf(jTextField1.getText());
            
        }
        //Summary/Dates
        if(jRadioButton2.isSelected()){
            if(dateChooserField1.getDate()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the begin Date");
                return;
            }
            
            if(dateChooserField2.getDate()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the end Date");
                return;
            }
            SavingsSummaryPdf s=new SavingsSummaryPdf();
            s.SavingsSummaryPdf(dateChooserField1.getDate(), dateChooserField2.getDate());
        }
        //statement
        if(jRadioButton3.isSelected()){
            if(dateChooserField3.getDate()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the begin Date");
                return;
            }
            
            if(dateChooserField4.getDate()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the end Date");
                return;
            }
            if(jTextField2.getText().isEmpty()){
                JOptionPane.showMessageDialog(this, "Kindly select the member no.");
                return;
            }
            SavingsStatementByMemberPdf s=new SavingsStatementByMemberPdf();
            s.SavingsStatementByMemberPdf(jTextField2.getText(), dateChooserField3.getDate(), dateChooserField4.getDate());
        }
        this.dispose();
    }//GEN-LAST:event_jButton2ActionPerformed

