    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        dialog=new CaretSearchDialog();
        String qry="select distinct(d.member_no), names, loan_no, amount_applied from loan_registration l, members_register m, debtors_ledger d "
                + "where  names ilike '%{f}%' and l.member_no=m.member_no and l.member_no=d.member_no "
                + "and d.member_no=m.member_no and paid=false  and approved=true group by 1, 2,3  having sum(debit-credit)>0.00";
        dialog.setSearchQuery(qry);
        AMSUtility.showSearchDialog(txtmemberno, dialog);
        Object [] object=dialog.getSelectedValue();
        if(object!=null){
            txtmemberno.setText(object[0].toString());
            txtmembername.setText(object[1].toString());
            txtloanno.setText(object[2].toString());
            txtloanamount.setText(object[3].toString());
        }
        
        double amountPayable=0.00, penalties=0.00, newAmountPayable=0.00, amountPaid=0.00, loanBalance=0.00;
        
        try {
            ResultSet rs=SQLHelper.getResultset(connect, "select sum(debit), sum(credit) from debtors_ledger "
                    + "where other_identifier='"+txtloanno.getText()+"' and member_no='"+txtmemberno.getText()+"' ");
            while(rs.next()){
                amountPayable=Math.ceil(rs.getDouble(1));
                amountPaid=Math.ceil(rs.getDouble(2));
            }
            System.err.println("Amount Payable: "+amountPayable);
            
            System.err.println("Amount Paid:    "+amountPaid);
            
            
            txtamountpayable.setText(""+amountPayable+"");
            
            txtamountpaid.setText(""+amountPaid+"");
            
            //loan balance is new amount payable less amount paid
            loanBalance=amountPayable-amountPaid;
            
            System.err.println("Balance:    "+loanBalance);
            
            txtbalance.setText(""+loanBalance+"");
            
            
        } catch (SQLException ex) {
            Logger.getLogger(DebtorsWriteOffIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

