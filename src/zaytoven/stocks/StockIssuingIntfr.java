    private void jXTable1KeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jXTable1KeyReleased
        Character ch=evt.getKeyChar();
        if(jXTable1.getSelectedColumn()==3){
            
            if(!Character.isDigit(ch)){
                JOptionPane.showMessageDialog(this, "Please enter quantity as a number");
                jXTable1.setValueAt(null, jXTable1.getSelectedRow(), 3);
                return;
            }
        }
        
        int existing=0, issuing=0, remainder=0;    
        if(jXTable1.getValueAt(jXTable1.getSelectedRow(), 3)!=null){
            issuing=Integer.parseInt(jXTable1.getValueAt(jXTable1.getSelectedRow(), 3).toString());
        }
        if(jXTable1.getValueAt(jXTable1.getSelectedRow(), 2)!=null){
            existing=Integer.parseInt(jXTable1.getValueAt(jXTable1.getSelectedRow(), 2).toString());
        }
        remainder=existing-issuing;
        if(remainder<0){
            JOptionPane.showMessageDialog(this, "You cannot issue more than the existing stock");
            jXTable1.setValueAt(0, jXTable1.getSelectedRow(), 3);
        }
        else{
            jXTable1.setValueAt(remainder, jXTable1.getSelectedRow(), 5);
            btnsave.setEnabled(true);
        }
        
        
    }//GEN-LAST:event_jXTable1KeyReleased

