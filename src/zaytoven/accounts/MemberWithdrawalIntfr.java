    private void txtwithdrawKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtwithdrawKeyReleased
        Character ch=evt.getKeyChar();
        if(!Character.isDigit(ch)){
            JOptionPane.showMessageDialog(this, "Amount to withdraw cannot contain alphabets");
            txtwithdraw.setText("");
        }
        
        double sharevalue=0.00, withdraw=0.00, balance=0.00;
        if(!txtsharevalue.getText().isEmpty()){
            sharevalue=Double.parseDouble(txtsharevalue.getText());
        }
        
        if(!txtwithdraw.getText().isEmpty()){
            withdraw=Double.parseDouble(txtwithdraw.getText());
        }
        balance=sharevalue-withdraw;
        txtbalance.setText(""+balance+"");
        if(balance<0.00){
            JOptionPane.showMessageDialog(this, "Balance cannot be negative");
            txtbalance.setText("0.00");
            txtwithdraw.setText("");
        }
    }//GEN-LAST:event_txtwithdrawKeyReleased


