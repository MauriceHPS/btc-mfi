    private void btnsearchinvestmentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsearchinvestmentActionPerformed
        dialog=new CaretSearchDialog();
        String qry="select id, creditor_id, supplier_names from investments_trail t, creditors_register c where "
                + "supplier_id=creditor_id and supplier_names ilike '%{f}%' order by 3";
        dialog.setSearchQuery(qry);
        AMSUtility.showSearchDialog(txtinvestmentid, dialog);
        Object [] object=dialog.getSelectedValue();
        if(object!=null){
            txtinvestmentid.setText(object[0].toString());
            txtcreditorno.setText(object[1].toString());
            txtcreditorname.setText(object[2].toString());
        }
        
        Date applicationDate=null, deductionDate=null, disbursementDate=null;
        try {
            SimpleDateFormat df=new SimpleDateFormat("yyyy-MM-dd");
            
            ResultSet rs=SQLHelper.getResultset(connect, "SELECT principal, interest_rate, duration_months, application_date::date, scheduled_payment,  "
                    + "deduction_commencement::date, disbursement_date::date, amount_payable, total_interest FROM public.investments_trail where id='"+txtinvestmentid.getText()+"' "
                            + "and creditor_id='"+txtcreditorno.getText()+"' ");
            while(rs.next()){
                txtprincipal.setText(String.valueOf(rs.getDouble(1)));
                txtinterest.setText(String.valueOf(rs.getDouble(2)));
                txtduration.setText(String.valueOf(rs.getInt(3)));
                
                applicationDate=df.parse(rs.getDate(4).toString());
                dateChooserField1.setDate(applicationDate);
                
                txtscheduledpayment.setText(String.valueOf(rs.getDouble(5)));
                
                deductionDate=df.parse(rs.getDate(6).toString());
                dateChooserField2.setDate(deductionDate);
                
                disbursementDate=df.parse(rs.getDate(7).toString());
                dateChooserField3.setDate(disbursementDate);
                
                txtamountpayable.setText(String.valueOf(rs.getDouble(8)));
                txttotalinterest.setText(String.valueOf(rs.getDouble(9)));
                
            }
        } catch (SQLException | ParseException ex) {
            Logger.getLogger(ReceivingInvestmentsIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnsearchinvestmentActionPerformed
    
