    private void jComboBox1ItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jComboBox1ItemStateChanged
       if(jComboBox1.getSelectedItem()==null){
           return;
       }
       Array fromDB=null;
       Object [] menuTests=null;
        String [] menuItems=null;
        try {
            ResultSet rs=SQLHelper.getResultset(connect, "select roles from group_roles where group_id=(select group_id from group_setup "
                    + "where group_name='"+jComboBox1.getSelectedItem()+"')");
            while(rs.next()){
                fromDB=rs.getArray(1);
                
                menuTests = (Object[]) fromDB.getArray();
            
                System.err.println("Menu items: "+menuTests);
                if(menuTests!=null){
                    menuItems=(String[]) fromDB.getArray();
                }
            }
            
        } catch (SQLException ex) {
            Logger.getLogger(GroupPriviligesAllocIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
        DefaultListModel listModel=new DefaultListModel();
        if(menuItems!=null){
            for (String menuItem : menuItems) {
                listModel.addElement(menuItem);
            }
        }
        else{
            listModel=new DefaultListModel();
        }
        jList2.setModel(listModel);
    }//GEN-LAST:event_jComboBox1ItemStateChanged

