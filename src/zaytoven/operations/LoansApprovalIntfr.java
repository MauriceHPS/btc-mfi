    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        int c=jTable1.getSelectedColumn();
        int r=jTable1.getSelectedRow();
        
        //loan profile pdf, and opening of attachments
        if(c==0 || c==1){
            String loanNo=null, memberNo=null;
        
            //auto open the loan profile
            if(jTable1.getValueAt(r, 0)!=null){
                loanNo=String.valueOf(jTable1.getValueAt(r, 0));
                memberNo=String.valueOf(jTable1.getValueAt(r, 1));
            }

            if(memberNo!=null && loanNo!=null){
                LoanProfilePdf l=new LoanProfilePdf();
                l.LoanProfilePdf(loanNo);

                String dir=null;
                try {
                    ResultSet rs=SQLHelper.getResultset(connect, "select guarantor_attached_copy_path1 from loan_registration where loan_no='"+loanNo+"' "
                            + "and member_no='"+memberNo+"' ");
                    while(rs.next()){
                        dir=rs.getString(1);
                    }

                    if(dir!=null){
                        //open the security items
                        File directory=new File(dir);
                        System.err.println("In Directory [String]:   "+directory);
                        
                        //open the directory containing the attachments
                        Desktop.getDesktop().open(directory);
                        
                        String [] toRead=directory.list();
                        System.err.println("To Read:    "+Arrays.toString(toRead));
                        File inner;
                        for(int i=0;i<toRead.length;i++){
                            inner=new File(toRead[i]);
                            System.err.println("Inner file path:    "+inner.getPath());
                            
                            //open every file in the directory
                            Desktop.getDesktop().open(new File(directory+"\\"+inner));
                        }
                    }
                } catch (SQLException | IOException ex) {
                    Logger.getLogger(LoansApprovalIntfr.class.getName()).log(Level.SEVERE, null, ex);
                }
            }
        }
        
        
        // approve or reject
        if(c==5){
            if(Objects.equals(jTable1.getValueAt(r, 5), Boolean.TRUE)){
                jTable1.setValueAt(false, r, 6);
            }
        }
        if(c==6){
            if(Objects.equals(jTable1.getValueAt(r, 6), Boolean.TRUE)){
                jTable1.setValueAt(false, r, 5);
            }
        }
    }//GEN-LAST:event_jTable1MouseClicked

