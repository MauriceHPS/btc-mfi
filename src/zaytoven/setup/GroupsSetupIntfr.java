    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if(jTextField2.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly input the group name");
            return;
        }
        PreparedStatement pr=null;
        try {
            connect.setAutoCommit(false);
            String groupID=null;
            ResultSet rs=SQLHelper.getResultset(connect, "select 'G' || nextval('group_id_seq')");
            while(rs.next()){
                groupID=rs.getString(1);
            }
            pr=connect.prepareStatement("insert into group_setup(group_id, group_name)values(?, upper(?))");
            pr.setString(1, groupID);
            pr.setString(2, jTextField2.getText());
            pr.executeUpdate();
            System.err.println(pr.toString());
            
           
            
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Insert is Successful");
                jTextField2.setText("");
            }
            
             connect.commit();
            connect.setAutoCommit(true);
            
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(GroupsSetupIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(GroupsSetupIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

