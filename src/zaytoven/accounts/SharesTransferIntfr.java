    private void validateBeforeSaving(){
        if(txtnewmemberno.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the member no. of the recipient");
            return;
        }
        if(txtnewmembername.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the member name of the recipient");
            return;
        }
        if(txtmemberno.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the source member no.");
            return;
        }
        if(txtmembername.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the source member name");
            return;
        }
        if(txtshareholdingamount.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the source's shareholding amount");
            return;
        }
        if(txtnewshareholdingvalue.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly input the amount you wish to transfer");
            return;
        }
        if(String.valueOf(jPasswordField1.getPassword()).isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly input the shares' transfer password");
            return;
        }
        
        if(!String.valueOf(jPasswordField1.getPassword()).equals("transfer2018")){
            JOptionPane.showMessageDialog(this, "Kindly input the correct passoword", "Wrong password!!", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        if(Double.parseDouble(txtnewshareholdingvalue.getText())<=0){
            JOptionPane.showMessageDialog(this, "The amount to transfer cannot be less than or equal to zero (0)");
            return;
        }
        insertDetails();
    }
    
    private void insertDetails(){
        
        PreparedStatement pr=null;
        String shareHoldersCode="C005-0031", savingsNo=null;
        
        try {
            connect.setAutoCommit(false);
            ResultSet rs=SQLHelper.getResultset(connect, "select 'SA' || nextval('savings_no_seq')");
            while(rs.next()){
                savingsNo=rs.getString(1);
            }
            
            //query to used to increase and decrease the respective shareholding values
            String sql="INSERT INTO savings_management(member_no, identifier, debit, credit, date, accounting_code, username, reasons)\n" +
                                                    "    VALUES (?, ?, ?::numeric, ?::numeric, ?::timestamp, ?, ?, ?)";
            
            //decrease the old member's shareholding value
            pr=connect.prepareStatement(sql);
            pr.setString(1, txtmemberno.getText());
            pr.setString(2, savingsNo);
            pr.setObject(3, txtnewshareholdingvalue.getText());
            pr.setDouble(4, 0.00);
            pr.setObject(5, "now()");
            pr.setString(6, shareHoldersCode);
            pr.setString(7, userName);
            pr.setString(8, "SHARES TRANSFER");
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            //increase the new member's shareholding value
            pr=connect.prepareStatement(sql);
            pr.setString(1, txtnewmemberno.getText());
            pr.setString(2, savingsNo);
            pr.setObject(4, txtnewshareholdingvalue.getText());
            pr.setDouble(3, 0.00);
            pr.setObject(5, "now()");
            pr.setString(6, shareHoldersCode);
            pr.setString(7, userName);
            pr.setString(8, "RECEIVING NEW SHARES");
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            
            
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Insert is Successful");
                resetDetails();
            }
            
            connect.commit();
            connect.setAutoCommit(true);
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(SharesTransferIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(SharesTransferIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    
