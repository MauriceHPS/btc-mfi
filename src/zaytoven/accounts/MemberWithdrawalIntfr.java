    private void insertDetails(){
        PreparedStatement pr=null;
        String shareHoldingCode="C005-0031", cashBookCode=null, identifier=null;
        try {
            connect.setAutoCommit(false);
            ResultSet rs=SQLHelper.getResultset(connect, "select code from payment_modes where mode='"+combopayment.getSelectedItem().toString()+"'");
            while(rs.next()){
                cashBookCode=rs.getString(1);
            }
            
            ResultSet rs1=SQLHelper.getResultset(connect, "select 'SA' || nextval('savings_no_seq')");
            while(rs1.next()){
                identifier=rs1.getString(1);
            }
            //query to be used to debit savings management and close account
            String savingsQuery="INSERT INTO savings_management(member_no, identifier, debit, credit, date, accounting_code, username)\n" +
                "    VALUES (?, ?, ?::numeric, ?::numeric, ?::timestamp, ?, ?)";
            pr=connect.prepareStatement(savingsQuery);
            pr.setString(1, txtmemberno.getText());
            pr.setString(2, identifier);
            pr.setObject(3, txtwithdraw.getText());
            pr.setDouble(4, 0.00);
            pr.setObject(5, dateChooserField1.getDate().toString());
            pr.setString(6, shareHoldingCode);
            pr.setString(7, userName);
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            //query to credit cash book to reflect mode of payout
            pr=connect.prepareStatement("INSERT INTO cash_book(accounting_code, category, debit, credit, date, username, identifier)"
                    + "VALUES (?, ?, ?::numeric, ?::numeric, ?::timestamp, ?, ?)");
            pr.setString(1, cashBookCode);
            pr.setString(2, "FUNDS WITHDRAWAL");
            pr.setDouble(3, 0.00);
            pr.setObject(4, txtwithdraw.getText());
            pr.setObject(5, dateChooserField1.getDate().toString());
            pr.setString(6, userName);
            pr.setString(7, identifier);
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            
            //GL query to respectively debit and credit cash used and shareholding reduction
            String glQuery="INSERT INTO general_ledger(username, identifier, category, description, accounting_code, debit, credit, entry_time)\n" +
                                    "    VALUES (?, ?, ?, ?, ?, ?::numeric, ?::numeric, ?::timestamp)";
            //shareHolders
            pr=connect.prepareStatement(glQuery);
            pr.setString(1, userName);
            pr.setString(2, identifier);
            pr.setString(3, "SHAREHOLDING VALUE REDUCTION");
            pr.setString(4, "OPERATING CAPITAL REDUCTION");
            pr.setString(5, shareHoldingCode);
            pr.setObject(6, txtwithdraw.getText());
            pr.setDouble(7, 0.00);
            pr.setObject(8, dateChooserField1.getDate().toString());
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            //cashbook in GL
            pr=connect.prepareStatement(glQuery);
            pr.setString(1, userName);
            pr.setString(2, identifier);
            pr.setString(3, "SHAREHOLDING VALUE REDUCTION");
            pr.setString(4, "FUNDS WITHDRAWAL BY MEMBER");
            pr.setString(5, cashBookCode);
            pr.setObject(7, txtwithdraw.getText());
            pr.setDouble(6, 0.00);
            pr.setObject(8, dateChooserField1.getDate().toString());
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Insert is Successful");
                resetDetails();
            }
            
            connect.commit();
            connect.setAutoCommit(true);
            
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(MemberWithdrawalIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(MemberWithdrawalIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    
