    private void txtamounttorecoverKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtamounttorecoverKeyReleased
        Character ch=evt.getKeyChar();
        
        if(Character.isAlphabetic(ch)){
            JOptionPane.showMessageDialog(this, "Amount to recover cannot contain any alphabets");
            txtamounttorecover.setText("0.00");
        }
        
        double currentBalance=0.00, toRecover=0.00, newBalance=0.00;
        
        if(!txtcurrentbalance.getText().isEmpty()){
            currentBalance=Double.parseDouble(txtcurrentbalance.getText());
        }
        
        if(!txtamounttorecover.getText().isEmpty()){
            toRecover=Double.parseDouble(txtamounttorecover.getText());
        }
        
        if(toRecover>currentBalance){
            JOptionPane.showMessageDialog(this, "Amount to Recover cannot be greater than the current balance");
            txtamounttorecover.setText("0.00");
        }
        
        newBalance=currentBalance-toRecover;
        txtnewbalance.setText(String.valueOf(newBalance));
    }//GEN-LAST:event_txtamounttorecoverKeyReleased

