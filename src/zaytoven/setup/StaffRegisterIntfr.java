    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if(buttonGroup1.getSelection()==null){
            JOptionPane.showMessageDialog(this, "Kindly select an option from the entry point window");
            return;
        }
        CaretSearchDialog dialog=new CaretSearchDialog();
        String qry="SELECT staff_id, names, gender, id_no, active  FROM staff_registration where names ilike '%{f}%' or staff_id ilike '%{f}%'";
         dialog.setSearchQuery(qry);
        AMSUtility.showSearchDialog(txtstaffid,dialog);
        Object[] selection = dialog.getSelectedValue();
        if (selection != null) {
            txtstaffid.setText(selection[0].toString());
            txtnames.setText(selection[1].toString());
            combogender.setSelectedItem(selection[2].toString());
            txtidno.setText(selection[3].toString());
            boolean active=(boolean) selection[4];
            checkactivation.setSelected(active);
        }
        Date regDate=null, actualDate=null, dob=null;
        SimpleDateFormat df=new SimpleDateFormat("dd-MM-yyyy");
        try {
            ResultSet rs=SQLHelper.getResultset(connect, "select registration_date, residence, tel_no, next_of_kin_names, "
                    + "next_of_kin_phoneno, relationship, next_of_kin_residence, dob from staff_registration where staff_id='"+txtstaffid.getText()+"'");
            while(rs.next()){
                regDate=rs.getDate(1);
                df.format(regDate);
                datereg.setDate(regDate);
                txtresidence.setText(rs.getString(2));
                txtphoneno.setText(rs.getString(3));
                txtkinnames.setText(rs.getString(4));
                txtkinphoneno.setText(rs.getString(5));
                txtkinrship.setText(rs.getString(6));
                txtkinresidence.setText(rs.getString(7));
                dob=rs.getDate(8);
                df.format(dob);
                dateChooserField1.setDate(dob);
            }
//            SimpleDateFormat df=new SimpleDateFormat("yyyy-MM-dd");
            datereg.setDate(regDate);
        } catch (SQLException ex) {
            Logger.getLogger(StaffRegisterIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton1ActionPerformed
    
