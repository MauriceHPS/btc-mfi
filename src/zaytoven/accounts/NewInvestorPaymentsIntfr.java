    private void txtamounttopayKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtamounttopayKeyReleased
        Character ch=evt.getKeyChar();
         if(Character.isAlphabetic(ch)){
             JOptionPane.showMessageDialog(this, "Amount to pay cannot contain alphabets");
             txtamounttopay.setText("");
         }
         
         double amountToPay=0.00, innerPrincipal=0.00, innerInterest=0.00, principalBalance=0.00, newPrincipalBalance=0.00, payoff=0.00;
         
         System.err.println("Interest Days:  "+interestDays);
         
         if(!txtamounttopay.getText().isEmpty()){
             amountToPay=Double.parseDouble(txtamounttopay.getText());
         }
         
         
         if(!txtprincipalbalance.getText().isEmpty()){
             principalBalance=Double.parseDouble(txtprincipalbalance.getText());
         }
         
         if(!txtpayoffamount.getText().isEmpty()){
             payoff=Double.parseDouble(txtpayoffamount.getText());
         }
         
         if(expectedInterestToRecover>=amountToPay){
             innerInterest=amountToPay;
             txtinnerinterest.setText(""+innerInterest+"");
             
             innerPrincipal=0.00;
             txtinnerprincipal.setText(""+innerPrincipal+"");
         }
         
         else{
            innerInterest=annualInterest*principalBalance*(interestDays/30);
            txtinnerinterest.setText(""+innerInterest+"");
            
            innerPrincipal=amountToPay-innerInterest;
            txtinnerprincipal.setText(""+innerPrincipal+"");
         }
         
         
         
         if(amountToPay>payoff){
             JOptionPane.showMessageDialog(this, "The amount to be paid cannot be greater than the pay off amount");
             txtamounttopay.setText("");
             txtinnerinterest.setText("0.00");
             txtinnerprincipal.setText("0.00");
         }
         
        newPrincipalBalance=payoff-(innerPrincipal+innerInterest);
        txtnewprincipalbalance.setText(""+newPrincipalBalance+"");
         
    }//GEN-LAST:event_txtamounttopayKeyReleased

    
