    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if(buttonGroup1.getSelection()==null){
            JOptionPane.showMessageDialog(this, "Kindly select an item from the radio buttons above");
        }
        if(radiosummary.isSelected()){
            if(dateChooserField1.getDate()==null){
                JOptionPane.showMessageDialog(this, "Kindly select the begin date");
                return;
            }

            if(dateChooserField2.getDate()==null){
                JOptionPane.showMessageDialog(this, "Kindly select the end date");
                return;
            }
            InvestorsSummaryPdf i=new InvestorsSummaryPdf();
            i.InvestorsSummaryPdf(dateChooserField1.getDate(), dateChooserField2.getDate());
        }
        
        if(radiostatement.isSelected()){
            if(txtcreditorno.getText().isEmpty()){
                JOptionPane.showMessageDialog(this, "Kindly select the creditor Details");
                return;
            }
            if(txtloanno.getText().isEmpty()){
                JOptionPane.showMessageDialog(this, "Kindly select the loan Details");
                return;
            }
            
            InvestorStatementPdf i=new InvestorStatementPdf();
            i.InvestorStatementPdf(txtcreditorno.getText(), txtloanno.getText());
        }
        jButton3.doClick();
    }//GEN-LAST:event_jButton2ActionPerformed

