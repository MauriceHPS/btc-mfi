    public String arrayToString(Object[] listObj) {
        String strToArray = listObj[0].toString();        
        for (int i = 1; i <listObj.length; i++) {            
            strToArray = strToArray+", "+listObj[i].toString();            
        }
        return strToArray;        
    }
    
