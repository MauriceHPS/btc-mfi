    private void jCheckBox1ItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jCheckBox1ItemStateChanged
        resetTable();
        try {
            ResultSet rs=SQLHelper.getResultset(connect, "SELECT L.ITEM_CODE, ITEM_NAME,L.quantity AS PACKS_SOLD, P.SELLING_PRICE, \n" +
"L.quantity*P.selling_price AS TOTAL FROM DEBTORS_LEDGER L, STOCK_ITEMS I, CUSTOMERS_REGISTRATION C, CUSTOMER_PRICES P \n" +
"                    WHERE C.CUSTOMER_ID=L.CUSTOMER_ID AND L.ITEM_CODE=I.ITEM_CODE AND L.ITEM_CODE=ITEM_NO AND I.ITEM_CODE=ITEM_NO  \n" +
"                    AND DEBT_NO = '"+txtdebtno.getText()+"' AND SPEC='SALES' and settled=false GROUP BY 1, 2, 3, 4");
            int r=0;
            while(rs.next()){
                jTable1.setValueAt(rs.getObject(1), r, 0);
                jTable1.setValueAt(rs.getObject(2), r, 1);
                jTable1.setValueAt(rs.getObject(3), r, 2);
                jTable1.setValueAt(rs.getObject(4), r, 3);
                jTable1.setValueAt(rs.getObject(5), r, 4);
                r++;
            }
        } catch (SQLException ex) {
            Logger.getLogger(ReturnInwardsIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jCheckBox1ItemStateChanged

    private void jTable1KeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jTable1KeyReleased
        int c=jTable1.getSelectedColumn(), r=jTable1.getSelectedRow(), qty=0;
        double price=0.00, remainder=0.00, currTotal=0.0;
        if(c==5){
            Character ch=evt.getKeyChar();
            if(!Character.isDigit(ch)){
                JOptionPane.showMessageDialog(this, "Column "+jTable1.getModel().getColumnName(5)+" cannot contain alphabets");
                jTable1.setValueAt(null, r, 5);
                return;
            }
        }
        if(jTable1.getValueAt(r, 5)!=null){
                qty=Integer.parseInt(jTable1.getValueAt(r, 5).toString());
            }
        if(jTable1.getValueAt(r, 3)!=null){
            price=Double.parseDouble(jTable1.getValueAt(r, 3).toString());
        }
        if(jTable1.getValueAt(r, 4)!=null){
            currTotal=Double.parseDouble(jTable1.getValueAt(r, 4).toString());
        }
        remainder=currTotal-(qty*price);
        jTable1.setValueAt(remainder, r, 6);
    }//GEN-LAST:event_jTable1KeyReleased

