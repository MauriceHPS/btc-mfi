    private void comboloantypeItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_comboloantypeItemStateChanged
        if(comboloantype.getSelectedItem()==null)return;
        
        try {
            ResultSet rs=SQLHelper.getResultset(connect, "select interest_rate, duration, minimum from loan_categories "
                    + "where loan_type='"+comboloantype.getSelectedItem().toString()+"'");
            while(rs.next()){
                txtinterest.setText(rs.getObject(1).toString());
                txtduration.setText(rs.getObject(2).toString());
                
                maximumDuration=rs.getInt(2);
                minimumDuration=rs.getInt(3);
            }
        } catch (SQLException ex) {
            Logger.getLogger(LoanRegistrationCompoundIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_comboloantypeItemStateChanged

