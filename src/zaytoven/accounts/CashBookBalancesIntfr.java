    private void jTable1KeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jTable1KeyReleased
        int c=jTable1.getSelectedColumn();
        int r=jTable1.getSelectedRow();
        
        Character ch=evt.getKeyChar();
        
        if(c==3){
            if(!Character.isDigit(ch)){
                JOptionPane.showMessageDialog(this, "Actual Value cannot contain any alphabets");
                jTable1.setValueAt(0, r, 3);
            }
        }
        
        double systemVal=0.00, actualVal=0.00, variance=0.00;
        
        if(jTable1.getValueAt(r, 2)!=null){
            systemVal=Double.parseDouble(jTable1.getValueAt(r, 2).toString());
        }
        System.err.println("System Value:   "+systemVal);
        
        if(jTable1.getValueAt(r, 3)!=null){
            actualVal=Double.parseDouble(jTable1.getValueAt(r, 3).toString());
        }
        System.err.println("Actual Value:   "+actualVal);
        
        variance=actualVal-systemVal;
        System.err.println("Variance:   "+variance);
        
        jTable1.setValueAt(variance, r, 4);
    }//GEN-LAST:event_jTable1KeyReleased
    
    private void resetDetails(){
        for(int i=0;i<jTable1.getRowCount();i++){
            for(int j=0;j<jTable1.getColumnCount();j++){
                jTable1.setValueAt(null, i, j);
            }
        }
        jCheckBox1.setSelected(false);
    }

