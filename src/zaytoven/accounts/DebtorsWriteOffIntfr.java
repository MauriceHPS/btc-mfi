    private void txtamounttowriteoffKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtamounttowriteoffKeyReleased
        Character ch=evt.getKeyChar();
        if(Character.isAlphabetic(ch)){
            JOptionPane.showMessageDialog(this, "Amount to Write-off cannot contain alphabets");
            txtamounttowriteoff.setText("");
        }
        
        double writeOff=0.00, balance=0.00;
        
        if(!txtamounttowriteoff.getText().isEmpty()){
            writeOff=Double.parseDouble(txtamounttowriteoff.getText());
        }
        
        if(!txtbalance.getText().isEmpty()){
            balance=Double.parseDouble(txtbalance.getText());
        }
        
        if(writeOff>balance){
            JOptionPane.showMessageDialog(this, "Amount to write-off cannot be greater than the loan balance");
            txtamounttowriteoff.setText("");
        }
    }//GEN-LAST:event_txtamounttowriteoffKeyReleased
    
