    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
        dialog=new CaretSearchDialog();
        String qry=null;
            qry="SELECT loan_no, l.member_no,  names FROM public.loan_registration l, members_register m where approved=true "
                    + "and m.member_no=l.member_no and names ilike '%{f}%'";
        dialog.setSearchQuery(qry);
        AMSUtility.showSearchDialog(txtloanno, dialog);
        Object [] object=dialog.getSelectedValue();
        if(object!=null){
            txtloanno.setText(object[0].toString());
            txtmemberno.setText(object[1].toString());
            txtmembername.setText(object[2].toString());
        }
        
        try {
            ResultSet rs=SQLHelper.getResultset(connect, " SELECT amount_applied, loan_type, amount_payable, duration_months, "
                    + "annual_interest_Rate, (amount_payable-amount_applied) as interest_amount, username FROM public.loan_registration "
                    + "where loan_no='"+txtloanno.getText()+"' ");
            while(rs.next()){
                txtamountapplied.setText(rs.getObject(1).toString());
                txtloantype.setText(rs.getString(2));
                txtamountpayable.setText(rs.getObject(3).toString());
                txtduration.setText(rs.getObject(4).toString());
                txtoldinterest.setText(rs.getObject(5).toString());
                txtinterestamount.setText(rs.getObject(6).toString());
                txtregistered.setText(rs.getString(7));
            }
        } catch (SQLException ex) {
            Logger.getLogger(LoanModificationIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        if(txtloanno.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the loan No");
            return;
        }
        PreparedStatement pr=null;
        try {
            connect.setAutoCommit(false);
            //insert into loans modification
            pr=connect.prepareStatement("INSERT INTO public.loans_modification(loan_no, modified_by,  entry_time)\n" +
                            "VALUES (?, ?, ?::timestamp)");
            pr.setString(1, txtloanno.getText());
            pr.setString(2, userName);
            pr.setObject(3, "now()");
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            //modify the necessary column values in loan registration
            pr=connect.prepareStatement("UPDATE public.loan_registration SET annual_interest_rate=?::numeric WHERE loan_no='"+txtloanno.getText()+"' ");
            pr.setObject(1, txtinterestrate.getText());
            pr.executeUpdate();
            System.err.println(pr.toString());
            
                //end
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Loan Modification was Successful");
                resetDetails();
            }
            
            connect.commit();
            connect.setAutoCommit(true);
            
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(LoanModificationIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(LoanModificationIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
        
    }//GEN-LAST:event_jButton3ActionPerformed

