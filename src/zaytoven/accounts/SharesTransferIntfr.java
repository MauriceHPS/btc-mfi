    private void txtnewshareholdingvalueKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtnewshareholdingvalueKeyReleased
        Character ch=evt.getKeyChar();
        if(Character.isAlphabetic(ch)){
            JOptionPane.showMessageDialog(this, "Amount to transfer cannot contain any alphabets");
            txtnewshareholdingvalue.setText("");
        }
        double newAmount=0.00, currentAmount=0.00;
        if(!txtshareholdingamount.getText().isEmpty()){
            currentAmount=Double.parseDouble(txtshareholdingamount.getText());
        }
        if(!txtnewshareholdingvalue.getText().isEmpty()){
            newAmount=Double.parseDouble(txtnewshareholdingvalue.getText());
        }
        if(newAmount>currentAmount){
            JOptionPane.showMessageDialog(this, "The amount to transfer cannot be greater than the current shareholding amount");
            txtnewshareholdingvalue.setText(""+0.00+"");
        }
    }//GEN-LAST:event_txtnewshareholdingvalueKeyReleased

