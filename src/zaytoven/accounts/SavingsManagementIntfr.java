    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        dialog=new CaretSearchDialog();
        String qry="select member_no, first_name||' '||last_name||' '||surname as name from members_register where first_name||' '||last_name||' '||surname ilike '%{f}%' "
                + "or member_no ilike '%{f}%'  and active=true";
        dialog.setSearchQuery(qry);
        AMSUtility.showSearchDialog(txtmemberno, dialog);
        Object [] object=dialog.getSelectedValue();
        if(object!=null){
            txtmemberno.setText(object[0].toString());
            txtmembernames.setText(object[1].toString());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

