    private void txtamountKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtamountKeyReleased
        Character ch=evt.getKeyChar();
        if(Character.isAlphabetic(ch)){
            JOptionPane.showMessageDialog(this, "Amount cannot contain alphabets");
            txtamount.setText("");
        }
        
        double balance=0.00, newBalance=0.00, amount=0.00;
        
        if(!txtbalance.getText().isEmpty()){
            balance=Double.parseDouble(txtbalance.getText());
        }
        
        if(!txtamount.getText().isEmpty()){
            amount=Double.parseDouble(txtamount.getText());
        }
        
        if(amount>balance){
            JOptionPane.showMessageDialog(this, "Amount to expense cannot be greater than the balance");
            txtamount.setText("");
            txtnewbalance.setText("");
        }
        newBalance=balance-amount;
        
        txtnewbalance.setText(""+newBalance+"");
    }//GEN-LAST:event_txtamountKeyReleased

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if(txtreqno.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the request No");
            return;
        }
        if(txtreason.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the reason");
            return;
        }
        if(txtamount.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly input the amount to expense");
            return;
        }
        if(jTextArea1.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly input the description");
            return;
        }
        
        PreparedStatement pr=null;
        String expenseID=null;
        try {
            connect.setAutoCommit(false);
            //get the expense ID
            ResultSet rs=SQLHelper.getResultset(connect, "select 'EXP' || nextval('petty_cash_expensing_id')");
            while(rs.next()){
                expenseID=rs.getString(1);
            }
            //insert into the audit trail
            pr=connect.prepareStatement("INSERT INTO petty_cash_expensing(requisition_no, description, accounting_code, amount, expensing_id, username)"
                    + "VALUES (?, ?, ?, ?::numeric, ?, ?)");
            pr.setString(1, txtreqno.getText());
            pr.setString(2, jTextArea1.getText());
            pr.setString(3, txtreasoncode.getText());
            pr.setObject(4, txtamount.getText());
            pr.setString(5, expenseID);
            pr.setString(6, userName);
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Insert is Successful");
                resetDetails();
            }
            
            connect.commit();
            connect.setAutoCommit(true);
            
            
            
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(PettyCashExpensesIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(PettyCashExpensesIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

