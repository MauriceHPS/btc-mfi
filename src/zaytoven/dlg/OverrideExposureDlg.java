    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if(String.valueOf(jPasswordField1.getPassword())==null){
            JOptionPane.showMessageDialog(this, "Kindly input the password");
            return;
        }
        String password=null;
        try {
            ResultSet rs=SQLHelper.getResultset(connect, "select distinct(a.username), password from access_control a, user_groups g "
                    + "where a.username=g.username and g.group_id in (select group_id from group_setup where group_name in ('ICT', 'EXECUTIVES')) "
                    + "and a.username='"+userName+"' ");
            while(rs.next()){
                password=rs.getString(2);
            }
        } catch (SQLException ex) {
            Logger.getLogger(OverrideExposureDlg.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        if(password==null){
            JOptionPane.showMessageDialog(this, "You are not authorized to override the exposure limit");
            return;
        }

        if(MD5Encrypter.encrypt(String.valueOf(jPasswordField1.getPassword())).equals(password)){
            setDecision("approved");
            this.dispose();
        }
        else{
            JOptionPane.showMessageDialog(this, "Wrong password");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

