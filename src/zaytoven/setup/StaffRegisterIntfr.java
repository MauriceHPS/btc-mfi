    private void insertDetails(){
        String sql="INSERT INTO staff_registration(staff_id, names, registration_date, gender, id_no, active, residence, tel_no, "
                + "next_of_kin_names, next_of_kin_phoneno, relationship, next_of_kin_residence, dob)"
                + "VALUES (?, upper(?), ?::date, ?, ?, ?::boolean, ?, ?, ?, ?, ?, ?, ?::date)";
        String staffID=null;
        int counter=0;
        PreparedStatement pr=null;
        try {
            connect.setAutoCommit(false);
            //AVOIDANCE OF STAFF DUPLICATION USING NATIONAL ID NO.
            ResultSet count=SQLHelper.getResultset(connect, "select count(id_no) from staff_registration where id_no='"+txtidno.getText()+"'");
            while(count.next()){
                counter=count.getInt(1);
            }
            if(counter>0){
                JOptionPane.showMessageDialog(this, "There exist a staff with the same details you are about to register.\n The system will not allow you to duplicate staff");
                btnsave.setEnabled(false);
            }
            else{
                    //getStaffID
                ResultSet rs=SQLHelper.getResultset(connect, "select 'STF' || nextval('staff_id_seq')");
                while(rs.next()){
                    staffID=rs.getString(1);
                }
                //insert into the DB
                pr=connect.prepareStatement(sql);
                pr.setString(1, staffID);
                pr.setString(2, txtnames.getText());
                pr.setObject(3, datereg.getDate().toString());
                pr.setObject(4, combogender.getSelectedItem());
                pr.setString(5, txtidno.getText());
                if(checkactivation.isSelected()){
                    pr.setBoolean(6, true);
                }
                else{
                    pr.setBoolean(6, false);
                }
                pr.setString(7, txtresidence.getText());
                pr.setString(8, txtphoneno.getText());
                pr.setString(9, txtkinnames.getText());
                pr.setString(10, txtkinphoneno.getText());
                pr.setString(11, txtkinrship.getText());
                pr.setString(12, txtkinresidence.getText());
                pr.setObject(13, dateChooserField1.getDate().toString());
                pr.executeUpdate();
                
                if(pr!=null){
                    JOptionPane.showMessageDialog(this, "Insert is Successful");
                    resetDetails();
                }
            }
            
            connect.commit();
            connect.setAutoCommit(true);
            
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(StaffRegisterIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(StaffRegisterIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    
