    private void pushFilesToDirectory(File [] file){
        File destination=null;
        for(File listItem : file){
            String address=listItem.getAbsolutePath();
            File source=new File(address);
            System.err.println("Source: "+address);
            
            //for updating details
            if(radioexisting.isSelected()){
                globalLoanNo=txtloanno.getText();
                globalMemberNo=txtmemberno.getText();
            }
            
            Properties getIpAddress=new Properties();
            
            String propertyFile=System.getProperty("user.dir") + System.getProperty("file.separator") + "SYSPROP.properties";
            
            try {
                getIpAddress.load(new FileInputStream(propertyFile));
            } catch (FileNotFoundException ex) {
                Logger.getLogger(LoanRegistrationCompoundIntfr.class.getName()).log(Level.SEVERE, null, ex);
            } catch (IOException ex) {
                Logger.getLogger(LoanRegistrationCompoundIntfr.class.getName()).log(Level.SEVERE, null, ex);
            }
            
            String ipAddress=getIpAddress.getProperty("host");
            
            System.err.println("Host Ip Address:    "+ipAddress);
            
            if(ipAddress.equalsIgnoreCase("localhost")){
                InetAddress add = null;
                String hostName=null;
                try {
                    add = InetAddress.getLocalHost();
                } catch (UnknownHostException ex) {
                    Logger.getLogger(LoanRegistrationCompoundIntfr.class.getName()).log(Level.SEVERE, null, ex);
                }
                hostName=add.getHostName();
                ipAddress=hostName;
            }
            
            System.err.println("Ip Address: "+ipAddress);
            
            destination=new File("\\\\"+ipAddress+"\\Scanned Files\\Loan Securities\\"+globalLoanNo+" - "+globalMemberNo);

            if(!destination.exists()){
                destination.mkdirs();
            }

            System.out.println("Destination:    "+destination.getPath());
            try {
                FileUtils.copyFileToDirectory(source, destination);
            } catch (IOException ex) {
                Logger.getLogger(SimpleFileCopIntfr.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
        txtfilepathguarantors.setText(destination.getPath());
    }
