    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        dialog=new CaretSearchDialog();
        String qry="select IDENTIFIER, date::date from LOAN_RECEIPTS where IDENTIFIER ilike '%{f}%' order by 2desc";
        dialog.setSearchQuery(qry);
        AMSUtility.showSearchDialog(jTextField1, dialog);
        Object [] object=dialog.getSelectedValue();
        if(object!=null){
            jTextField1.setText(object[0].toString());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if(buttonGroup1.getSelection()==null){
            JOptionPane.showMessageDialog(this, "Kindly select a radio button above");
            return;
        }
        //By ID
        if(jRadioButton1.isSelected()){
            if(jTextField1.getText().isEmpty()){
                JOptionPane.showMessageDialog(this, "Kindly select the Identifier");
                return;
            }
            ReceivingLoanPaymentByIDPdf r=new ReceivingLoanPaymentByIDPdf();
            r.ReceivingLoanPaymentByIDPdf(jTextField1.getText());
        }
        //Summary/Dates
        if(jRadioButton2.isSelected()){
            if(dateChooserField1.getDate()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the begin Date");
                return;
            }
            
            if(dateChooserField2.getDate()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the end Date");
                return;
            }
            ReceivingLoanPaymentsSummPdf r=new ReceivingLoanPaymentsSummPdf();
            r.ReceivingLoanPaymentsSummPdf(dateChooserField1.getDate(), dateChooserField2.getDate());
        }
        this.dispose();
    }//GEN-LAST:event_jButton2ActionPerformed

