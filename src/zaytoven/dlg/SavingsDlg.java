    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        if(buttonGroup1.getSelection()==null){
            JOptionPane.showMessageDialog(this, "Kindly select a radio button above");
            return;
        }
        dialog=new CaretSearchDialog();
        String qry="select distinct(s.member_no), first_name||' '||last_name||' '||surname as names from savings_management s, members_register m \n" +
"                                    where s.member_no=m.member_no and s.member_no ilike '%{f}%' or first_name||' '||last_name||' '||surname ilike '%{f}%' ";
        dialog.setSearchQuery(qry);
        AMSUtility.showSearchDialog(jTextField2, dialog);
        Object [] object=dialog.getSelectedValue();
        if(object!=null){
            jTextField2.setText(object[0].toString());
        }
    }//GEN-LAST:event_jButton4ActionPerformed

