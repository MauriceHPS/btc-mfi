    private void jCheckBox1ItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jCheckBox1ItemStateChanged
        int i=0;
        String sql="select distinct(order_id), o.item_code, item_name, date_ordered, quantity_ordered, buying_price, quantity_ordered*buying_price as total "
                + "from stock_orders o, stock_items i where i.item_code=o.item_code and approved=false and delivered=false";
        try {
            ResultSet rs=SQLHelper.getResultset(connect, sql);
            while(rs.next()){
                jTable1.setValueAt(rs.getObject(1), i, 0);
                jTable1.setValueAt(rs.getObject(2), i, 1);
                jTable1.setValueAt(rs.getObject(3), i, 2);
                jTable1.setValueAt(rs.getObject(4), i, 3);
                jTable1.setValueAt(rs.getObject(5), i, 4);
                jTable1.setValueAt(rs.getObject(6), i, 5);
                jTable1.setValueAt(rs.getObject(7), i, 6);
                i++;
            }
        } catch (SQLException ex) {
            Logger.getLogger(OrdersApprovalIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jCheckBox1ItemStateChanged

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        PreparedStatement pr=null;
        try {
            connect.setAutoCommit(false);
            for(int i=0;i<jTable1.getRowCount();i++){
                if(jTable1.getValueAt(i, 0)!=null && jTable1.getValueAt(i, 1)!=null && jTable1.getValueAt(i, 2)!=null && jTable1.getValueAt(i, 3)!=null && 
                        jTable1.getValueAt(i, 4)!=null && jTable1.getValueAt(i, 5)!=null &  jTable1.getValueAt(i, 6)!=null && jTable1.getValueAt(i, 7)==Boolean.TRUE){
                    //insert into orders_approval
                    pr=connect.prepareStatement("INSERT INTO orders_approval(order_id, item_code, username)VALUES (?, ?, ?)");
                    pr.setObject(1, jTable1.getValueAt(i, 0));
                    pr.setObject(2, jTable1.getValueAt(i, 1));
                    pr.setString(3, userName);
                    pr.executeUpdate();
                    System.err.println(pr.toString());

                    //update stock orders set approved to true for the order no and item code
                    pr=connect.prepareStatement("UPDATE stock_orders  SET  approved=true WHERE order_id='"+jTable1.getValueAt(i, 0)+"' "
                            + "and item_code='"+jTable1.getValueAt(i, 1)+"'");
                    
                    pr.executeUpdate();
                    System.err.println(pr.toString());
                }
            }
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Approval was Successful");
                resetDetails();
            }
            connect.commit();
            connect.setAutoCommit(true);
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(OrdersApprovalIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(OrdersApprovalIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

