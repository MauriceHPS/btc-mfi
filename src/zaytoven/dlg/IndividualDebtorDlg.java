    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
        dialog=new CaretSearchDialog();
        String qry="select distinct(loan_no), d.member_no,  names from members_register m, loan_registration l , \n" +
"                        debtors_ledger d   where l.member_no=m.member_no and m.member_no=d.member_no and l.member_no=d.member_no "
                + "and loan_no=other_identifier  and names ilike '%{f}%' and approved=true";

        dialog.setSearchQuery(qry);
        AMSUtility.showSearchDialog(jTextField1, dialog);
        Object [] object=dialog.getSelectedValue();
        if(object!=null){
            jTextField1.setText(object[1].toString());
            jTextField2.setText(object[0].toString());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

