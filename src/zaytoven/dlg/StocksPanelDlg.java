    private void searchButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchButton2ActionPerformed
        CaretSearchDialog dialog=new CaretSearchDialog();
        String qry=null;
        
        //orders
        if(radioorders.isSelected()){
            qry="select distinct(order_id), date_ordered from stock_orders where order_id ilike '%{f}%' order by 2 desc";
            dialog.setSearchQuery(qry);
            AMSUtility.showSearchDialog(txtid, dialog);
            Object [] object=dialog.getSelectedValue();
            if(object!=null){
                txtid.setText(object[0].toString());
            }
        }
        // receiving
        if(radioreceiving.isSelected()){
            qry="select distinct(receiving_no), receiving_date from st_receiving_issuing where receiving_no ilike '%{f}%' order by 2 desc";
            dialog.setSearchQuery(qry);
            AMSUtility.showSearchDialog(txtid, dialog);
            Object [] object=dialog.getSelectedValue();
            if(object!=null){
                txtid.setText(object[0].toString());
            }
        }
        //issuing
        if(radioissuing.isSelected()){
            qry="select distinct(issue_no), issuing_date from st_receiving_issuing where issue_no ilike '%{f}%' order by 2 desc";
            dialog.setSearchQuery(qry);
            AMSUtility.showSearchDialog(txtid, dialog);
            Object [] object=dialog.getSelectedValue();
            if(object!=null){
                txtid.setText(object[0].toString());
            }
        }
    }//GEN-LAST:event_searchButton2ActionPerformed

    private void btnokActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnokActionPerformed
        if(buttonGroup1.getSelection()==null){
            JOptionPane.showMessageDialog(this, "Kindly select an item from the radio buttons above");
            return;
        }
        if(txtid.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select an ID from the text field above");
            return;
        }
        if(radioorders.isSelected()){
            OrdersPdf fees=new OrdersPdf();
            fees.OrdersPdf(con, String.valueOf(txtid.getText()));
        }
        
        if(radioreceiving.isSelected()){
            StocksReceivingPdf receiving=new StocksReceivingPdf();
            receiving.StocksReceivingPdf(txtid.getText());
        }
        
        if(radioissuing.isSelected()){
            StocksIssuingPdf issue=new StocksIssuingPdf();
            issue.StocksIssuingPdf(con, txtid.getText());
        }
        this.dispose();
    }//GEN-LAST:event_btnokActionPerformed

