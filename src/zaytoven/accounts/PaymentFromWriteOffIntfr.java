    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        dialog=new CaretSearchDialog();
        String qry="select d.identifier, d.member_no, names from debtors_writeoff d, members_register m where d.member_no=m.member_no \n" +
                        "and names ilike '%{f}%' group by 1, 2, 3 having sum(credit-debit)>0 ";
        dialog.setSearchQuery(qry);
        AMSUtility.showSearchDialog(txtwriteoffno, dialog);
        Object [] object=dialog.getSelectedValue();
        if(object!=null){
            txtwriteoffno.setText(object[0].toString());
            txtmemberno.setText(object[1].toString());
            txtmembername.setText(object[2].toString());
        }
        
        //loan no, write off value
        try {
            ResultSet rs=SQLHelper.getResultset(connect, "select loan_no, credit from debtors_writeoff where identifier='"+txtwriteoffno.getText()+"' "
                    + "order by date ASC limit 1");
            while(rs.next()){
                txtloanno.setText(rs.getString(1));
                txtwriteoffamount.setText(String.valueOf(rs.getDouble(2)));
            }
            
            //recovered amount
            ResultSet rs1=SQLHelper.getResultset(connect, "select case when sum(debit) is null then 0.00 else sum(debit) end as case1 from debtors_writeoff "
                    + "where identifier='"+txtwriteoffno.getText()+"' ");
            while(rs1.next()){
                txtrecoveredamount.setText(String.valueOf(rs1.getDouble(1)));
            }
            
            //recoverable write off amount
            ResultSet rs2=SQLHelper.getResultset(connect, "select case when sum(credit-debit) is null then 0.00 else sum(credit-debit) end as case1 "
                    + "from debtors_writeoff where identifier='"+txtwriteoffno.getText()+"'  ");
            while(rs2.next()){
                txtcurrentbalance.setText(String.valueOf(rs2.getDouble(1)));
            }
        } catch (SQLException ex) {
            Logger.getLogger(PaymentFromWriteOffIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

