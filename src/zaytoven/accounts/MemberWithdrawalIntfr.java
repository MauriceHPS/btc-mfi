    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        dialog=new CaretSearchDialog();
        String qry="select member_no, first_name||' '||last_name||' '||surname as names from members_register where active=true "
                + "and member_no ilike '%{f}%' or first_name||' '||last_name||' '||surname ilike '%{f}%' ";
        dialog.setSearchQuery(qry);
        AMSUtility.showSearchDialog(txtmemberno, dialog);
        Object [] object=dialog.getSelectedValue();
        if(object!=null){
            txtmemberno.setText(object[0].toString());
            txtmembername.setText(object[1].toString());
        }
        try {
            ResultSet rs=SQLHelper.getResultset(connect, "select case when sum(credit-debit) is null then 0.00 else sum(credit-debit) end as case1 "
                    + "from savings_management where member_no='"+txtmemberno.getText()+"'");
            while(rs.next()){
                txtsharevalue.setText(rs.getObject(1).toString());
            }
        } catch (SQLException ex) {
            Logger.getLogger(MemberWithdrawalIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

