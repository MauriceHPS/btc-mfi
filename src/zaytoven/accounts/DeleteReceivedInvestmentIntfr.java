    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        dialog=new CaretSearchDialog();
        String qry="select l.identifier, loan_no, l.member_no, names from loan_receipts l, members_register m \n" +
                        "where m.member_no=l.member_no and names ilike '%{f}%'";
        dialog.setSearchQuery(qry);
        AMSUtility.showSearchDialog(txtpaymentid, dialog);
        Object [] object=dialog.getSelectedValue();
        if(object!=null){
            txtpaymentid.setText(object[0].toString());
            txtloanno.setText(object[1].toString());
            txtmemberno.setText(object[2].toString());
            txtmembername.setText(object[3].toString());
        }
        
        double principal=0.00, paymentReceived=0.00;
        try {
            ResultSet rs=SQLHelper.getResultset(connect, "select amount_applied from loan_registration where loan_no='"+txtloanno.getText()+"' "
                    + "and member_no='"+txtmemberno.getText()+"'");
            while(rs.next()){
                principal=rs.getDouble(1);
            }
            System.err.println("Principal:  "+principal);
            txtprincipal.setText(""+principal+"");
            
            ResultSet rs1=SQLHelper.getResultset(connect, "select amount from loan_receipts where identifier='"+txtpaymentid.getText()+"'");
            while(rs1.next()){
                paymentReceived=rs1.getDouble(1);
            }
            
            System.err.println("Payment Received:   "+paymentReceived);
            
            txtamountreceived.setText(""+paymentReceived+"");
        } catch (SQLException ex) {
            Logger.getLogger(DeleteReceivedInvestmentIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if(txtpaymentid.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the payment ID");
            return;
        }
        PreparedStatement pr=null;
        try {
            connect.setAutoCommit(false);
            
            //trail for all deleted payments
            pr=connect.prepareStatement("INSERT INTO public.deleted_received_payments(identifier, loan_no, member_no, amount, username)\n" +
"	VALUES (?, ?, ?, ?::numeric, ?);");
            pr.setString(1, txtpaymentid.getText());
            pr.setString(2, txtloanno.getText());
            pr.setString(3, txtmemberno.getText());
            pr.setObject(4, txtamountreceived.getText());
            pr.setString(5, userName);
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            
//            delete from debtors_ledger
             pr=connect.prepareStatement("DELETE FROM public.debtors_ledger WHERE receiving_payment_id='"+txtpaymentid.getText()+"' \n" +
            "and description='PAYMENT RECEIVED  FROM MEMBER';");
            pr.executeUpdate();
            System.err.println(pr.toString());

//            delete from loan_receipts
            pr=connect.prepareStatement("DELETE FROM public.loan_receipts WHERE identifier='"+txtpaymentid.getText()+"'");
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            
//            delete from cash_book
            pr=connect.prepareStatement("DELETE FROM public.cash_book WHERE identifier='"+txtpaymentid.getText()+"'");
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            
//            delete from general_ledger
            pr=connect.prepareStatement("DELETE FROM public.general_ledger WHERE identifier='"+txtpaymentid.getText()+"' and description='MEMBER PAYMENT' ");
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            //check whether the member still has a loan balance , after deleting the transaction
            double difference=0.00;
            
            ResultSet rss1=SQLHelper.getResultset(connect, "select case when sum(debit-credit) is null then 0.00 else sum(debit-credit) end as case1 from "
                    + "debtors_ledger where other_identifier='"+txtloanno.getText()+"' and member_no='"+txtmemberno.getText()+"' ");
            while(rss1.next()){
                difference=rss1.getDouble(1);
            }
            System.err.println("Amount Receivable: "+difference);
            //set paid to false if difference >0
            if(difference>0.00){
                pr=connect.prepareStatement("update debtors_ledger set paid=false where other_identifier='"+txtloanno.getText()+"' "
                        + "and member_no='"+txtmemberno.getText()+"' ");
                pr.executeUpdate();
                System.err.println(pr.toString());
            }
            
            //set paid to true if difference <=0
            else{
                pr=connect.prepareStatement("update debtors_ledger set paid=true where other_identifier='"+txtloanno.getText()+"' "
                        + "and member_no='"+txtmemberno.getText()+"' ");
                pr.executeUpdate();
                System.err.println(pr.toString());
            }
            
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Deletion was successful");
                resetDetails();
            }
            connect.commit();
            connect.setAutoCommit(true);
        
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(DeleteReceivedInvestmentIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(DeleteReceivedInvestmentIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        
        
    }//GEN-LAST:event_jButton1ActionPerformed

