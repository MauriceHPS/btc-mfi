    private void jTable10MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable10MouseClicked
        if(jTable10.getSelectedColumn()==1 || jTable1.getSelectedColumn()==2){
            if(buttonGroup2.getSelection()==null){
                JOptionPane.showMessageDialog(this, "Inorder to proceed, you must select one of the radio buttons above");
                return;
            }
            dialog=new CaretSearchDialog();
            String qry=null;

            //Current Assets
            if(radiocurrentassetscr.isSelected()){
                qry="select  sub_code, name from coa_specifics where name='"+combocurrentassetscr.getSelectedItem().toString()+"' --and name ilike '%{f}%' "
                        + "union "
                        + "select level2_code, name  from coal_level2 where level1_code =(select sub_code from coa_specifics "
                        + "where name='"+combocurrentassetscr.getSelectedItem().toString()+"') --and name ilike '%{f}%'";
                dialog.setSearchQuery(qry);
                AMSUtility.showSearchDialog(jTable10, dialog);
                Object [] object=dialog.getSelectedValue();
                if(object!=null){
                    jTable10.setValueAt(object[0], jTable10.getSelectedRow(), 1);
                    jTable10.setValueAt(object[1], jTable10.getSelectedRow(), 2);
                }
                jTable10.setValueAt(combocurrentassetscr.getSelectedItem(), jTable10.getSelectedRow(), 0);
            }
        }
        
        double totalCredit=0.00;
        if(!txtcredit.getText().isEmpty()){
            totalCredit=Double.parseDouble(txtcredit.getText());
        }
        
        if(jTable10.getSelectedColumn()==5){
            if(jTable10.getValueAt(jTable10.getSelectedRow(), 4)!=null && Objects.equals(jTable10.getValueAt(jTable10.getSelectedRow(), 5), Boolean.TRUE)){
                totalCredit+=Double.parseDouble(jTable10.getValueAt(jTable10.getSelectedRow(), 4).toString());
                txtcredit.setText(""+totalCredit+"");
            }
            if(jTable10.getValueAt(jTable10.getSelectedRow(), 4)!=null && Objects.equals(jTable10.getValueAt(jTable10.getSelectedRow(), 5), Boolean.FALSE)){
                totalCredit-=Double.parseDouble(jTable10.getValueAt(jTable10.getSelectedRow(), 4).toString());
                txtcredit.setText(""+totalCredit+"");
            }
        }
    }//GEN-LAST:event_jTable10MouseClicked

