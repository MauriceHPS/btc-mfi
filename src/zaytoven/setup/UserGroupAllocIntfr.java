    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if(jComboBox1.getSelectedItem()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the username");
            return;
        }
        
        if(jComboBox2.getSelectedItem()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the group name");
            return;
        }
        PreparedStatement pr=null;
        try {
            connect.setAutoCommit(false);
            String groupID=null;
            ResultSet rs=SQLHelper.getResultset(connect, "select group_id from group_setup where group_name='"+jComboBox2.getSelectedItem().toString()+"'");
            while(rs.next()){
                groupID=rs.getString(1);
            }
            pr=connect.prepareStatement("insert into user_groups(username, group_id)values(?, ?)");
            pr.setObject(1, jComboBox1.getSelectedItem());
            pr.setString(2, groupID);
            pr.executeUpdate();
            
            System.err.println(pr.toString());
            
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Insert is Successful");
                jComboBox1.setSelectedItem(null);
                jComboBox2.setSelectedItem(null);
            }
            
            connect.commit();
            connect.setAutoCommit(true);
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(UserGroupAllocIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(UserGroupAllocIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

