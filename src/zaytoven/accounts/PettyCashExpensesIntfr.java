    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        dialog=new CaretSearchDialog();
        String qry="SELECT REQUISITION_NO, AMOUNT FROM PETTY_CASH_REQUISITION "
                + "WHERE APPROVED=TRUE AND EXPENSED=FALSE AND REQUISITION_NO ILIKE '%{f}%' ";
        dialog.setSearchQuery(qry);
        AMSUtility.showSearchDialog(txtreqno, dialog);
        Object [] object=dialog.getSelectedValue();
        if(object!=null){
            txtreqno.setText(object[0].toString());
            txtdebit.setText(object[1].toString());
        }
        double initialDebit=0.00, used=0.00, balance=0.00;
        
        if(!txtdebit.getText().isEmpty()){
            initialDebit=Double.parseDouble(txtdebit.getText());
        }
        
        try {
            ResultSet rs=SQLHelper.getResultset(connect, "SELECT CASE WHEN SUM(AMOUNT) IS NOT NULL THEN  SUM(AMOUNT) ELSE 0.00 END AS CASE1 "
                    + "FROM PETTY_CASH_EXPENSING WHERE REQUISITION_NO ='"+txtreqno.getText()+"'");
            while(rs.next()){
                used=rs.getDouble(1);
                txtamountused.setText(""+used+"");
            }
        } catch (SQLException ex) {
            Logger.getLogger(PettyCashExpensesIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
        balance=initialDebit-used;
        txtbalance.setText(""+balance+"");
    }//GEN-LAST:event_jButton1ActionPerformed

