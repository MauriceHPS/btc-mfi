    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
       resetTable();
        if(txtprincipal.getText().isEmpty()){
           JOptionPane.showMessageDialog(this, "Kindly input the desired loan amount");
           return;
       }
       if(txtduration.getText().isEmpty()){
           JOptionPane.showMessageDialog(this, "Kindly input the desired duration for the loan");
           return;
       }
       if(txtinterest.getText().isEmpty()){
           JOptionPane.showMessageDialog(this, "Kindly select the desired loan type to auto populate the interest rate field");
           return;
       }
       if(dateChooserField2.getDate()==null){
           JOptionPane.showMessageDialog(this, "Kindly select the deduction commencement date");
           return;
       }
        
        double principal=0.00, rate=0.00, time=0.00,  totalAmountPayable=0.00, interest=0.00, 
               advocateFee=0.00, processingFee=0.00, insuranceFee=0.00, monthlyPayment=0.00;
       
       if(!txtprincipal.getText().isEmpty()){
           principal=Double.parseDouble(txtprincipal.getText());
       }
       
       if(!txtinterest.getText().isEmpty()){
           rate=Double.parseDouble(txtinterest.getText());
       }
       
       if(!txtduration.getText().isEmpty()){
           time=Double.parseDouble(txtduration.getText());
       }
       
       advocateFee=Double.parseDouble(txtadvocatefees.getText());
       
       interest=principal*(rate/100)*time;
       
       
       processingFee=(Double.parseDouble(txtprocessingcharge.getText())/100)*principal;
       insuranceFee=(Double.parseDouble(txtinsurance.getText())/100)*principal;
       
       double totalProcessing=advocateFee+processingFee+insuranceFee;
       
       
       totalAmountPayable=(principal+interest);
       txtamountpayable.setText(""+totalAmountPayable+"");
       
       amountToDisburse=principal-totalProcessing;
       txtamounttodisburse.setText(""+amountToDisburse+"");
       
       monthlyPayment=totalAmountPayable/time;
       txtmonthlyinstallment.setText(""+monthlyPayment+"");
       
       double innerPayable=0.00, netBalance=0.00;
       Date innerDate=null;
       for(int i=1;i<=time;i++){
           jTable1.setValueAt(i, (i-1), 0);
           
           if(i==1){
               innerPayable=totalAmountPayable;
               netBalance=innerPayable-monthlyPayment;
               SimpleDateFormat df=new SimpleDateFormat("dd-MM-yyyy");
               String d=df.format(dateChooserField2.getDate());
               try {
                   innerDate=df.parse(d);
               } catch (ParseException ex) {
                   Logger.getLogger(LoanRegistrationSimpleIntIntfr.class.getName()).log(Level.SEVERE, null, ex);
               }
               
               
               System.err.println("Formatted dateChooserField2.getDate():   "+innerDate);
               
               jTable1.setValueAt(innerPayable, (i-1), 1);
               jTable1.setValueAt(monthlyPayment, (i-1), 2);
               jTable1.setValueAt(netBalance, (i-1), 3);
               jTable1.setValueAt(innerDate, (i-1), 4);
           }
           else{
               innerPayable=netBalance;
               netBalance=innerPayable-monthlyPayment;
               
               //increment row i-1 date by 1 month;
               try {
                   ResultSet rs=SQLHelper.getResultset(connect, "select (date '"+innerDate+"' + interval '1 Month')::date");
                   while(rs.next()){
                       innerDate=rs.getDate(1);
                   }
               } catch (SQLException ex) {
                   Logger.getLogger(LoanRegistrationSimpleIntIntfr.class.getName()).log(Level.SEVERE, null, ex);
               }
               
               jTable1.setValueAt(innerPayable, (i-1), 1);
               jTable1.setValueAt(monthlyPayment, (i-1), 2);
               jTable1.setValueAt(netBalance, (i-1), 3);
               jTable1.setValueAt(innerDate, (i-1), 4);
           }
       }
    }//GEN-LAST:event_jButton2ActionPerformed

