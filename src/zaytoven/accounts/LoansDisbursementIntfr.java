    private String getDisbursementNo(){
        String sequenceNo=null;
            
         ResultSet rs;
        try {
            rs = SQLHelper.getResultset(connect, "select 'DS' || nextval('disburse_no_seq')");
            while(rs.next()){            
                sequenceNo=rs.getString(1);        
            }
        } catch (SQLException ex) {
            Logger.getLogger(LoansDisbursementIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
        disburseNo=sequenceNo;
        
        return sequenceNo;
    }
    
    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // find a way to avoid displaying of phone numbers that have already maxed out their disbursements
        dialog=new CaretSearchDialog();
        String qry="select loan_no, l.member_no, names from loan_registration l, members_register m \n" +
                            "where m.member_no=l.member_no and approved=true and disbursed=false and names ilike '%{f}%' ";
        dialog.setSearchQuery(qry);
        AMSUtility.showSearchDialog(txtloanno, dialog);
        Object [] object=dialog.getSelectedValue();
        if(object!=null){
            txtloanno.setText(object[0].toString());
            txtmemberno.setText(object[1].toString());
            txtmembername.setText(object[2].toString());
        }
        try {
           ResultSet rs1=SQLHelper.getResultset(connect, "select amount_applied, application_date, annual_interest_rate, duration_months, deduction_commencement, disbursement_date "
                   + "from loan_registration where loan_no='"+txtloanno.getText()+"' ");
           while(rs1.next()){
               txtamountapplied.setText(rs1.getObject(1).toString());
               txtregistrationdate.setText(rs1.getObject(2).toString());
               txtinterestrate.setText(rs1.getObject(3).toString());
               txtduration.setText(rs1.getObject(4).toString());
               txtdeductiondate.setText(rs1.getObject(5).toString());
               disbursementDate=rs1.getDate(6);
           }
            
            ResultSet rs=SQLHelper.getResultset(connect, "select case when sum(amount_disbursed) is null then 0.00 else sum(amount_disbursed) end as case1 "
                    + "from loan_disbursements where loan_no='"+txtloanno.getText()+"'");
            while(rs.next()){
                txtamountdisbursed.setText(rs.getObject(1).toString());
            }
        
            double balance=0.00, amountdisbursed=0.00, amountapplied=0.00;

            if(!txtamountapplied.getText().isEmpty()){
                amountapplied=Double.parseDouble(txtamountapplied.getText());
            }
            if(!txtamountdisbursed.getText().isEmpty()){
                amountdisbursed=Double.parseDouble(txtamountdisbursed.getText());
            }
            if(balance<0.00){
                JOptionPane.showMessageDialog(this, "Balance cannot contain any negative values");
                return;
            }
            balance=amountapplied-amountdisbursed;
            txtbalance.setText(""+balance+"");

            Date interestDate=null;


            System.err.println("Disbursement Date [during calculation of interest accrued]:  "+disbursementDate);

            ResultSet rr3;

            //get  Interest Days
            rr3 = SQLHelper.getResultset(connect, "select date::date from loan_interests where loan_no='"+txtloanno.getText()+"' "
                        + "and member_no='"+txtmemberno.getText()+"' ORDER BY date desc LIMIT 1");
            while(rr3.next()){
                interestDate=rr3.getDate(1);
            }

            System.err.println("Last Interest Date: "+interestDate);

            ResultSet rss;
            //calculation of interest days
            if(interestDate==null){
                rss=SQLHelper.getResultset(connect, "select current_date - '"+disbursementDate+"' ");
                while(rss.next()){
                    interestDays=rss.getDouble(1);
                }
            }

            else {
                rss=SQLHelper.getResultset(connect, "select current_date - '"+interestDate+"' ");
                while(rss.next()){
                    interestDays=rss.getDouble(1);
                }
            }

            System.err.println("Interest Days:   "+interestDays);

            txtinterestdays.setText(""+interestDays+"");
            } catch (SQLException ex) {
                Logger.getLogger(LoansDisbursementIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void txtamounttodisburseKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtamounttodisburseKeyReleased
        Character ch=evt.getKeyChar();
        if(Character.isAlphabetic(ch)){
            JOptionPane.showMessageDialog(this, "Amount to disburse cannot contain any alphabets");
            txtamounttodisburse.setText("");
        }
        double amountToDisburse=0.00, amountApplied=0.00, amountDisbursed=0.00;
        
        if(!txtamounttodisburse.getText().isEmpty()){
            amountToDisburse=Double.parseDouble(txtamounttodisburse.getText());
        }
        
        if(!txtamountapplied.getText().isEmpty()){
            amountApplied=Double.parseDouble(txtamountapplied.getText());
        }
        
        if(!txtamountdisbursed.getText().isEmpty()){
            amountDisbursed=Double.parseDouble(txtamountdisbursed.getText());
        }
        
        double newBalance=amountApplied-(amountDisbursed+amountToDisburse);
        txtbalance.setText(""+newBalance+"");
        
        if(newBalance<0.00){
            JOptionPane.showMessageDialog(this, "The outstanding disbursable balance cannot be negative. "
                    + "\nAll details will be wiped out to avoid arithmetic errors");
            resetDetails();
            return;
        }
        
    }//GEN-LAST:event_txtamounttodisburseKeyReleased
    
