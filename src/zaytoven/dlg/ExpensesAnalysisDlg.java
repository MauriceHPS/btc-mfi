    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        dialog=new CaretSearchDialog();
        String qry="select sub_code, name from coa_specifics where sub_code ilike '%{f}%' or name ilike '%{f}%' "
                + "union "
                + "select level2_code, name from coal_level2 where level2_code ilike '%{f}%' or name ilike '%{f}%'";
        dialog.setSearchQuery(qry);
        AMSUtility.showSearchDialog(jTextField1, dialog);
        Object [] object =dialog.getSelectedValue();
        if(object!=null){
            jTextField1.setText(object[0].toString());
            jTextField2.setText(object[1].toString());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if(jTextField1.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the Expense Code");
            return;
        }
        if(dateChooserField1.getDate()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the begin date");
            return;
        }
        if(dateChooserField2.getDate()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the end date");
            return;
        }
        ExpensesAnalysisPdf e=new ExpensesAnalysisPdf();
        e.ExpensesAnalysisPdf(jTextField1.getText(), dateChooserField1.getDate(), dateChooserField2.getDate());
        
        this.dispose();
    }//GEN-LAST:event_jButton2ActionPerformed

