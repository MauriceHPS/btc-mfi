    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if(dateChooserField1.getDate()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the begin date");
            return;
        }
        if(dateChooserField2.getDate()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the end date");
            return;
        }
        switch(controller){
//            case 1: {
//                MembersDebtorsSummaryPdf d=new MembersDebtorsSummaryPdf();
//                d.MembersDebtorsSummaryPdf(dateChooserField1.getDate(), dateChooserField2.getDate());
//                break;
//            }
            case 3: {
                CreditorsSummaryPdf m=new CreditorsSummaryPdf();
                m.CreditorsSummaryPdf(dateChooserField1.getDate(), dateChooserField2.getDate());
                break;
            }
            case 4:{
                StatementofProfitLossPdf s=new StatementofProfitLossPdf();
                s.StatementofProfitLossPdf(dateChooserField1.getDate(), dateChooserField2.getDate());
                break;
            }
            case 6:{
                OrdersSummaryPdf o=new OrdersSummaryPdf();
                o.OrdersSummaryPdf(dateChooserField1.getDate(), dateChooserField2.getDate());
                break;
            }
            case 7:{
                ApprovedLoansPdf l=new ApprovedLoansPdf();
                l.ApprovedLoansPdf(dateChooserField1.getDate(), dateChooserField2.getDate());
                break;
            }
            case 8:{
                LoansNotApprovedPdf l=new LoansNotApprovedPdf();
                l.LoansNotApprovedPdf(dateChooserField1.getDate(), dateChooserField2.getDate());
                break;
            }
            case 9:{
                DormantMembersSummaryPdf d=new DormantMembersSummaryPdf();
                d.DormantMembersSummaryPdf(dateChooserField1.getDate(), dateChooserField2.getDate());
                break;
            }
            case 10:{
                ApprovedOrdersSummaryPdf a=new ApprovedOrdersSummaryPdf();
                a.ApprovedOrdersSummaryPdf(dateChooserField1.getDate(), dateChooserField2.getDate());
                break;
            }
            case 11:{
                NotApprovedOrdersSummaryPdf n=new NotApprovedOrdersSummaryPdf();
                n.NotApprovedOrdersSummaryPdf(dateChooserField1.getDate(), dateChooserField2.getDate());
                break;
            }
            case 12:{
                LoansDisbursementsSummaryPdf l=new LoansDisbursementsSummaryPdf();
                l.LoansDisbursementsSummaryPdf(dateChooserField1.getDate(), dateChooserField2.getDate());
                break;
            }
            case 13:{
                CashBookSummaryPdf c=new CashBookSummaryPdf();
                c.CashBookSummaryPdf(dateChooserField1.getDate(), dateChooserField2.getDate());
                break;
            }
            case 14:{
                CashBookVarianceSummaryPdf c=new CashBookVarianceSummaryPdf();
                c.CashBookVarianceSummaryPdf(dateChooserField1.getDate(), dateChooserField2.getDate());
            }
            default: 
                break;
        }
        jButton2.doClick();
    }//GEN-LAST:event_jButton1ActionPerformed

