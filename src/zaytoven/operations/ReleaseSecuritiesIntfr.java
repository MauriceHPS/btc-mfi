    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        PreparedStatement pr=null;
        
        //sql insert statement
        String sql="INSERT INTO public.release_securities(loan_no, member_no, username)VALUES (?, ?, ?)";
        
        Properties getIpAddress=new Properties();
            
        String propertyFile=System.getProperty("user.dir") + System.getProperty("file.separator") + "SYSPROP.properties";

        try {
            getIpAddress.load(new FileInputStream(propertyFile));
        } catch (FileNotFoundException ex) {
            Logger.getLogger(LoanRegistrationCompoundIntfr.class.getName()).log(Level.SEVERE, null, ex);
        } catch (IOException ex) {
            Logger.getLogger(LoanRegistrationCompoundIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }

        String ipAddress=getIpAddress.getProperty("host");

        System.err.println("Host Ip Address:    "+ipAddress);

        if(ipAddress.equalsIgnoreCase("localhost")){
            InetAddress add = null;
            String hostName=null;
            try {
                add = InetAddress.getLocalHost();
            } catch (UnknownHostException ex) {
                Logger.getLogger(LoanRegistrationCompoundIntfr.class.getName()).log(Level.SEVERE, null, ex);
            }
            hostName=add.getHostName();
            ipAddress=hostName;
        }

        System.err.println("Ip Address: "+ipAddress);
        
        
        //source and destination directories
        File srcDir, destDir= new File("\\\\"+ipAddress+"\\Scanned Files\\Released Securities"), finalDest;
        
        String  loanNo=null, memberNo=null, concat=null;
        try {
            connect.setAutoCommit(false);
            for(int i=0;i<jTable1.getRowCount();i++){
                if(jTable1.getValueAt(i, 0)!=null && jTable1.getValueAt(i, 1)!=null && jTable1.getValueAt(i, 2)!=null && jTable1.getValueAt(i, 3)!=null && 
                        jTable1.getValueAt(i, 4)!=null && jTable1.getValueAt(i, 5)==Boolean.TRUE){
                    
                    //source directory from jTable [retrieved from DB]
                    srcDir=new File(String.valueOf(jTable1.getValueAt(i, 4)));
                    System.out.println("Source Directory:   "+srcDir.getAbsolutePath());
                    
                    loanNo=String.valueOf(jTable1.getValueAt(i, 0));
                    System.err.println("Loan No:    "+loanNo);
                    
                    memberNo=String.valueOf(jTable1.getValueAt(i, 1));
                    System.out.println("Member No:  "+memberNo);
                    
                    concat=loanNo+" - "+memberNo;
                    System.err.println("Concatenation of Loan No and Member No: "+concat);
                    
                    //destination directory
                    finalDest=new File(destDir+"\\"+concat);
                    System.out.println("Destination Directory:  "+finalDest.getAbsolutePath());
                    //if destination does not exist create it
                    
                    if(!finalDest.exists()){
                        finalDest.mkdirs();
                    }
                    //move dir from source to destination
                    FileUtils.moveDirectoryToDirectory(srcDir, finalDest, false);
                    
                    //DML insert
                    pr=connect.prepareStatement(sql);
                    pr.setObject(1, jTable1.getValueAt(i, 0));
                    pr.setObject(2, jTable1.getValueAt(i, 1));
                    pr.setString(3, userName);
                    pr.executeUpdate();
                    System.err.println(pr.toString());
                }
            }
            
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Releasing of Securities was Successful");
                resetDetails();
            }
            
            connect.commit();
            connect.setAutoCommit(true);
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(ReleaseSecuritiesIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(ReleaseSecuritiesIntfr.class.getName()).log(Level.SEVERE, null, ex);
        } catch (IOException ex) {
            Logger.getLogger(ReleaseSecuritiesIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
        
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jCheckBox1ItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jCheckBox1ItemStateChanged
        String sql="select other_identifier, d.member_no, names, amount_applied, guarantor_attached_copy_path1 from loan_registration l, \n" +
                        "members_register m, debtors_ledger d \n" +
                    "where l.loan_no=other_identifier and l.member_no=m.member_no and l.member_no=d.member_no and m.member_no=d.member_no \n" +
                    "and paid=true and other_identifier not in (select distinct(loan_no) from release_securities) group by 1, 2, 3, 4, 5 having sum(debit-credit)=0.00";
        int i=0;
        try {
            ResultSet rs=SQLHelper.getResultset(connect, sql);
            while(rs.next()){
                jTable1.setValueAt(rs.getObject(1), i, 0);
                jTable1.setValueAt(rs.getObject(2), i, 1);
                jTable1.setValueAt(rs.getObject(3), i, 2);
                jTable1.setValueAt(rs.getObject(4), i, 3);
                jTable1.setValueAt(rs.getObject(5), i, 4);
                i++;
            }
        } catch (SQLException ex) {
            Logger.getLogger(ReleaseSecuritiesIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jCheckBox1ItemStateChanged

