    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if(jTextField2.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly input the group name");
            return;
        }
        
        if(jTextField3.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly input the group type");
            return;
        }
        
        if(dateChooserField1.getDate()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the registration date");
            return;
        }
        
        if(jTextField4.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly input the credit officer");
            return;
        }
        
        if(jTextField5.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly input the meeting venue");
            return;
        }
        
        String groupID=null;
        PreparedStatement pr=null;
        try {
            connect.setAutoCommit(false);
            int count=0;
            ResultSet rs1=SQLHelper.getResultset(connect, "select count(group_id) from member_groups where group_name ilike '"+jTextField2.getText()+"' ");
            while(rs1.next()){
                count=rs1.getInt(1);
            }
            if(count>0){
                JOptionPane.showMessageDialog(this, "Group Already Exists.", "Avoiding Duplication!!!", JOptionPane.INFORMATION_MESSAGE);
                return;
            }
            
            ResultSet rs=SQLHelper.getResultset(connect, "select 'MG' || nextval('member_group_seq')");
            while(rs.next()){
                groupID=rs.getString(1);
            }
            pr=connect.prepareStatement("INSERT INTO member_groups(group_id, group_name, group_type, registration_date, credit_officer, meeting_venue)"
                    + "VALUES (?, upper(?), ?, ?::date, ?, ?)");
            pr.setString(1, groupID);
            pr.setString(2, jTextField2.getText());
            pr.setString(3, jTextField3.getText());
            pr.setObject(4, dateChooserField1.getDate().toString());
            pr.setString(5, jTextField4.getText());
            pr.setString(6, jTextField5.getText());
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Insert is Successful");
                resetDetails();
            }
            connect.commit();
            connect.setAutoCommit(true);
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(MemberGroupsIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(MemberGroupsIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

