    private void updateData(){
        PreparedStatement pr=null;
        
        try {
            connect.setAutoCommit(false);
            
            //UPDATE INVESTMENTS TRAIL DETAILS FOR THE ID [INVESTMENT NO] 
            pr=connect.prepareStatement("UPDATE public.investments_trail SET creditor_id=?, principal=?::numeric, interest_rate=?::numeric, "
                    + "duration_months=?::integer, application_date=?::date, scheduled_payment=?::numeric, deduction_commencement=?::date,  "
                    + "disbursement_date=?::date, amount_payable=?::numeric, total_interest=?::numeric WHERE id='"+txtinvestmentid.getText()+"' ");
            pr.setString(1, txtcreditorno.getText());
            pr.setDouble(2, Double.parseDouble(txtprincipal.getText()));
            pr.setDouble(3, Double.parseDouble(txtinterest.getText()));
            pr.setObject(4, txtduration.getText());
            pr.setObject(5, dateChooserField1.getDate().toString());
            pr.setObject(6, txtscheduledpayment.getText());
            pr.setObject(7, dateChooserField2.getDate().toString());
            pr.setObject(8, dateChooserField3.getDate().toString());
            pr.setObject(9, txtamountpayable.getText());
            pr.setObject(10, txttotalinterest.getText());
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            
            //UPDATE CREDITORS LEDGER SET CREDIT= PRINCIPAL WHERE IDENTIFIER= [INVESTMENT NO] AND DESCRIPTION='INVESTMENT RECEIVED'
            pr=connect.prepareStatement("UPDATE public.creditors_ledger SET creditor_id=?, credit=?::numeric "
                    + "WHERE identifier='"+txtinvestmentid.getText()+"' AND DESCRIPTION='INVESTMENT RECEIVED'");
            pr.setString(1, txtcreditorno.getText());
            pr.setObject(2, txtprincipal.getText());
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            //UPDATE CASH BOOK SET DEBIT=PRINCIPAL WHERE IDENTIFIER= [INVESTMENT NO] AND CATEGORY='INVESTMENT RECEIVED'
            pr=connect.prepareStatement("UPDATE public.cash_book SET debit="+Double.parseDouble(txtprincipal.getText())+"::numeric "
                    + "WHERE identifier='"+txtinvestmentid.getText()+"' AND CATEGORY='INVESTMENT RECEIVED'");
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            //UPDATE GENERAL LEDGER SET DEBIT=PRINCIPAL WHERE IDENTIFIER=[INVESTMENT NO] AND DESCRIPTION='INVESTMENT RECEIVED AS PAYABLE LOAN'
            // AND ACCOUNTING_CODE='C002-0059'
            pr=connect.prepareStatement("UPDATE public.general_ledger	SET  debit="+txtprincipal.getText()+"::numeric, other_identifier='"+txtcreditorno.getText()+"' "
                    + "WHERE identifier='"+txtinvestmentid.getText()+"' AND DESCRIPTION='INVESTMENT RECEIVED AS PAYABLE LOAN' "
                            + "AND ACCOUNTING_CODE='C002-0059'");
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            //UPDATE GENERAL LEDGER SET CREDIT=PRINCIPAL WHERE IDENTIFIER=[INVESTMENT NO] AND DESCRIPTION='INVESTMENT RECEIVED AS PAYABLE LOAN'
            // AND ACCOUNTING_CODE='C004-0018'
            pr=connect.prepareStatement("UPDATE public.general_ledger	SET  credit="+txtprincipal.getText()+"::numeric, other_identifier='"+txtcreditorno.getText()+"' "
                    + "WHERE identifier='"+txtinvestmentid.getText()+"' AND DESCRIPTION='INVESTMENT RECEIVED AS PAYABLE LOAN' "
                            + "AND ACCOUNTING_CODE='C004-0018'");
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Update is Successful");
                resetDetails();
            }
            
            connect.commit();
            connect.setAutoCommit(true);
            
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(ReceivingInvestmentsIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(ReceivingInvestmentsIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    
