    private void calculateInterest(){
           double recoverablePrincipal=0.00;
           
            try {
                //recoverable principal
                ResultSet rs11=SQLHelper.getResultset(connect, "select case when sum(debit-credit) is null then 0.00 else sum(debit-credit) end as case1 from debtors_ledger "
                        + "where other_identifier='"+txtloanno.getText()+"' and member_no='"+txtmemberno.getText()+"' ");
                while(rs11.next()){
                    recoverablePrincipal=rs11.getDouble(1);
                }
                
                System.err.println("Recoverable Principal:  "+recoverablePrincipal);
                
                
                System.err.println("Interest Days before loop entry:  "+interestDays);
         

                double newRecoverablePrincipal=recoverablePrincipal;

                System.err.println("New Recoverable Principal before Loop entry:   "+newRecoverablePrincipal);
                
                annualInterest=Double.parseDouble(txtinterestrate.getText())/100;
                
                System.err.println("Interest [decimal]  "+annualInterest);

                expectedInterestToRecover=0.00;
                
                if(newRecoverablePrincipal>0.00){
                    while(interestDays>=30){
                        System.err.println("Interest Days [Pre execution]: "+interestDays);

                        double innerInterest=Math.ceil(annualInterest*newRecoverablePrincipal);

                        if(interestDays>=30){
                            System.err.println("Inner Interest for the first 30 days is "+innerInterest);
                        }

                        expectedInterestToRecover+=innerInterest;

                        newRecoverablePrincipal+=expectedInterestToRecover;

                        System.err.println("Principal Balance + Interest: "+newRecoverablePrincipal);

                        System.err.println("Expected Interest to Recover [Loop]:   "+expectedInterestToRecover);

                        interestDays-=30;

                        System.err.println("Interest Days [After loop execution]: "+interestDays);
                    }

                        System.err.println("Interest Days [After loop exit]: "+interestDays);

                        double innerInterest=Math.ceil((annualInterest*newRecoverablePrincipal)*(interestDays/30));

                       System.err.println("Inner Interest for "+interestDays+" is "+innerInterest);

                       expectedInterestToRecover+=innerInterest;

                        System.err.println("Expected Interest to Recover:  "+expectedInterestToRecover);

                        double payoff=expectedInterestToRecover+recoverablePrincipal;

                        System.err.println("Pay off:   "+payoff);
                    }

                } catch (SQLException ex) {
                Logger.getLogger(LoansDisbursementIntfr.class.getName()).log(Level.SEVERE, null, ex);
            }
            
            if(expectedInterestToRecover>0.00){
                afterInterestCalculation();
            }
            else{
                insertDetails();
            }
    }
    
