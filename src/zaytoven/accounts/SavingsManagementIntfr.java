    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if(txtmemberno.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the member no");
            return;
        }
        if(txtmembernames.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the member name");
            return;
        }
        if(dateChooserField1.getDate()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the date");
            return;
        }
        if(txtamount.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly input the amount you wish to save");
            return;
        }
        if(combopaymentmode.getSelectedItem()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the mode of payment");
            return;
        }
        PreparedStatement pr=null;
        try {
            connect.setAutoCommit(false);
            String savingNo=null;
            ResultSet rs=SQLHelper.getResultset(connect, "select  'SA' || nextval('savings_no_seq')");
            while(rs.next()){
                savingNo=rs.getString(1);
            }
            
            String shareHoldingCode=null;
            ResultSet rs1=SQLHelper.getResultset(connect, "select sub_code from coa_specifics where name='SHAREHOLDERS VALUATION'");
            while(rs1.next()){
                shareHoldingCode=rs1.getString(1);
            }
            
            String cashBookCode=null;
            ResultSet rs2=SQLHelper.getResultset(connect, "select code from payment_modes where mode='"+combopaymentmode.getSelectedItem().toString()+"'");
            while(rs2.next()){
                cashBookCode=rs2.getString(1);
            }
            
            pr=connect.prepareStatement("INSERT INTO savings_management(member_no, identifier, debit, credit, date, accounting_code, username)\n" +
                                            "    VALUES (?, ?, ?::numeric, ?::numeric, ?::timestamp, ?, ?)");
            pr.setString(1, txtmemberno.getText());
            pr.setString(2, savingNo);
            pr.setDouble(3, 0.00);
            pr.setObject(4, txtamount.getText());
            pr.setObject(5, dateChooserField1.getDate().toString());
            pr.setString(6, shareHoldingCode);
            pr.setString(7, userName);
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            //cash book entry based on mode of payment
            pr=connect.prepareStatement("INSERT INTO cash_book(accounting_code, category, debit, credit, date, username, identifier)\n" +
                                                        "    VALUES (?, ?, ?::numeric, ?::numeric, ?::timestamp, ?, ?)");
            pr.setString(1, cashBookCode);
            pr.setString(2, "MEMBER SAVINGS");
            pr.setObject(3, txtamount.getText());
            pr.setDouble(4, 0.00);
            pr.setObject(5, dateChooserField1.getDate().toString());
            pr.setString(6, userName);
            pr.setString(7, savingNo);
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            //GENERAL LEDGER INSERT QUERY
            String gl="INSERT INTO general_ledger(username, identifier, category, description, accounting_code, debit, credit, entry_time, other_identifier)\n" +
                            "    VALUES (?, ?, ?, ?, ?, ?::numeric, ?::numeric, ?::timestamp, ?)";
            
            //general ledger for increase in cash
            pr=connect.prepareStatement(gl);
            pr.setString(1, userName);
            pr.setString(2, savingNo);
            pr.setString(3, "MEMBER SAVINGS");
            pr.setString(4, "LIQUIDITY INCREASE RESULTING FROM MEMBER SAVINGS");
            pr.setString(5, cashBookCode);
            pr.setObject(6, txtamount.getText());
            pr.setDouble(7, 0.00);
            pr.setObject(8, dateChooserField1.getDate().toString());
            pr.setString(9, txtmemberno.getText());
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            //general ledger credit for increase in shareholding
            pr=connect.prepareStatement(gl);
            pr.setString(1, userName);
            pr.setString(2, savingNo);
            pr.setString(3, "MEMBER SAVINGS");
            pr.setString(4, "SHARE CAPITAL INCREASE RESULTING FROM MEMBER SAVINGS");
            pr.setString(5, shareHoldingCode);
            pr.setObject(7, txtamount.getText());
            pr.setDouble(6, 0.00);
            pr.setObject(8, dateChooserField1.getDate().toString());
            pr.setString(9, txtmemberno.getText());
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Insert is Successful");
                resetDetails();
            }
            connect.commit();
            connect.setAutoCommit(true);
            
            SavingsByIDPdf s=new SavingsByIDPdf();
            s.SavingsByIDPdf(savingNo);
            
        } catch (SQLException ex) {
            try {
                connect.setAutoCommit(false);
            } catch (SQLException ex1) {
                Logger.getLogger(SavingsManagementIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(SavingsManagementIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

