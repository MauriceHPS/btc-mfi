    private void jCheckBox1ItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jCheckBox1ItemStateChanged
        if(!jCheckBox1.isSelected()) return;
        
        String accountingCode=null, accountName=null;
        
        ResultSet rs, rs1;
        int i=0;
        try {
            rs=SQLHelper.getResultset(connect, "select sub_code, name from coa_specifics where master_code='C002' and category='bank'");
            while(rs.next()){
                accountingCode=rs.getString(1);
                accountName=rs.getString(2);
                
                System.err.println("Accounting Code:    "+accountingCode);
                System.err.println("Account Name:   "+accountName);
                
                double value=0.00;
                rs1=SQLHelper.getResultset(connect, "select case when sum(debit-credit) is null then 0.00 else sum(debit-credit) end as case1 "
                        + "from GENERAL_LEDGER where accounting_code='"+accountingCode+"' ");
                while(rs1.next()){
                    value=rs1.getDouble(1);
                }
                
                System.err.println("System value:   "+value);
                
                jTable1.setValueAt(accountingCode, i, 0);
                jTable1.setValueAt(accountName, i, 1);
                jTable1.setValueAt(value, i, 2);
                i++;
            }
        } catch (SQLException ex) {
            Logger.getLogger(CashBookBalancesIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jCheckBox1ItemStateChanged

    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        if(!jCheckBox1.isSelected()){
            JOptionPane.showMessageDialog(this, "Kindly select the checkbox above");
            return;
        }
        PreparedStatement pr=null;
        String transactionID=null;
        try {
            connect.setAutoCommit(false);
            ResultSet rs=SQLHelper.getResultset(connect, "select 'CB' || nextval('cash_book_variance_id')");
            while(rs.next()){
                transactionID=rs.getString(1);
            }
            
            System.err.println("Transaction ID: "+transactionID);
            
            for(int i=0;i<jTable1.getRowCount();i++){
                if(jTable1.getValueAt(i, 0)!=null && jTable1.getValueAt(i, 1)!=null && jTable1.getValueAt(i, 2)!=null && jTable1.getValueAt(i, 3)!=null && 
                        jTable1.getValueAt(i, 4)!=null){
                    pr=connect.prepareStatement("INSERT INTO public.cash_book_variance(accounting_code, system_value, actual_value, transaction_id,"
                            + " username)VALUES (?, ?::numeric, ?::numeric, ?, ?)");
                    pr.setObject(1, jTable1.getValueAt(i, 0));
                    pr.setObject(2, jTable1.getValueAt(i, 2));
                    pr.setObject(3, jTable1.getValueAt(i, 3));
                    pr.setString(4, transactionID);
                    pr.setString(5, userName);
                    pr.executeUpdate();
                    System.err.println(pr.toString());
                }
            }
            
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Insert is Successful");
                resetDetails();
            }
            
            connect.commit();
            connect.setAutoCommit(true);
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(CashBookBalancesIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(CashBookBalancesIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
        
    }//GEN-LAST:event_btnsaveActionPerformed

