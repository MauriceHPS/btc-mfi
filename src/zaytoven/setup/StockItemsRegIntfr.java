    private void updatingData(){
        PreparedStatement pr=null;
        try {
            connect.setAutoCommit(false);
            for(int i=0;i<jXTable2.getRowCount();i++){
                if(jXTable2.getModel().getValueAt(i, 0)!=null && jXTable2.getModel().getValueAt(i, 1)!=null && jXTable2.getModel().getValueAt(i, 2)!=null && 
                    jXTable2.getModel().getValueAt(i, 3)!=null && jXTable2.getModel().getValueAt(i, 4)!=null && jXTable2.getModel().getValueAt(i, 5)!=null){
                    int count=0;
                    ResultSet rs=SQLHelper.getResultset(connect, "select count(item_code) from stock_items where item_code='"+jXTable2.getValueAt(i, 0).toString()+"' ");
                    while(rs.next()){
                        count=rs.getInt(1);
                    }
                    System.err.println("Count is  "+count);
                
                
                    if(count>0){
                        pr=connect.prepareStatement("UPDATE stock_items   SET item_name=INITCAP(?), buying_price=?::numeric(10, 2),    supplier_id=?, category=?,  "
                        + "min_stock_count=?::int WHERE item_code='"+jXTable2.getValueAt(i, 0).toString()+"'");
                        pr.setObject(1, jXTable2.getValueAt(i, 1).toString());
                        pr.setObject(2, jXTable2.getValueAt(i, 2).toString());
                        pr.setObject(3, jXTable2.getValueAt(i, 3).toString());
                        pr.setObject(4, jXTable2.getValueAt(i, 4).toString());
                        pr.setObject(5, jXTable2.getValueAt(i, 5).toString());
                        pr.executeUpdate();
                        System.err.println(pr.toString());
                    }
                }
            }
            
            
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Update is Successful");
                    resetDetails();
                    btnreset.doClick();
                }
            connect.commit();
            connect.setAutoCommit(true);
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(StockItemsRegIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(StockItemsRegIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
