    private void validateInfo(){
        if(txtmemberno.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the member no");
            return;
        }
        if(txtmembername.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the member name");
            return;
        }
        if(!jCheckBox1.isSelected()){
            JOptionPane.showMessageDialog(this, "Kindly click on the checkbox to confirm suspension");
            return;
        }
        if(txtreason.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly input the reason for suspension");
            return;
        }
        if(dateChooserField1.getDate()==null){
            JOptionPane.showMessageDialog(this, "Kindly select the current date");
            return;
        }
        
        insertDetails();
    }
    
    private void insertDetails(){
        PreparedStatement pr=null;
        try {
            connect.setAutoCommit(false);
            pr=connect.prepareStatement("INSERT INTO suspended_accounts(member_no, reason, date, username)VALUES (?, ?, ?::timestamp, ?)");
            pr.setString(1, txtmemberno.getText());
            pr.setString(2, txtreason.getText());
            pr.setObject(3, dateChooserField1.getDate().toString());
            pr.setString(4, userName);
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            pr=connect.prepareStatement("update members_register set active=false where member_no='"+txtmemberno.getText()+"'");
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Insert is Successful");
                resetDetails();
            }
            
            connect.commit();
            connect.setAutoCommit(true);
            
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(SuspendMemberAccountIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(SuspendMemberAccountIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
        
    }
    
    private void resetDetails(){
        txtmemberno.setText("");
        txtmembername.setText("");
        jCheckBox1.setSelected(false);
        txtreason.setText("");
        dateChooserField1.setDate(null);
    }
    
