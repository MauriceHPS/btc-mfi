    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        JFileChooser j=new JFileChooser();
        
        j.setMultiSelectionEnabled(false);
        
        j.setAcceptAllFileFilterUsed(false);
        j.setFileFilter(new FileNameExtensionFilter("PNG", "png"));
        j.setFileFilter(new FileNameExtensionFilter("GIF", "gif"));
        j.setFileFilter(new FileNameExtensionFilter("JPG", "jpg"));
        j.setFileFilter(new FileNameExtensionFilter("JPEG", "jpeg"));
        
        j.showOpenDialog(jPanel1);
        File file=j.getSelectedFile();
        jTextField4.setText(file.getAbsolutePath());
        
        try {
            bufferedImage=ImageIO.read(new File(file.getAbsolutePath()));
        } catch (IOException ex) {
            Logger.getLogger(SimpleFileCopIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
        SwingWorker sw = new SwingWorker() {
            @Override
            protected Object doInBackground(){
                try {
                    Thread.sleep(2500);//simulate large image takes long to load
                    icon = new ImageIcon(scaleImage(200, 160, bufferedImage));
                } catch (InterruptedException ex) {
                    Logger.getLogger(SimpleFileCopIntfr.class.getName()).log(Level.SEVERE, null, ex);
                } catch (Exception ex) {
                    Logger.getLogger(SimpleFileCopIntfr.class.getName()).log(Level.SEVERE, null, ex);
                }
                
                return null;
            }

            @Override
            protected void done() { 
                super.done();
                photolabel.setIcon(icon);
            }
        };
        sw.execute();
    }//GEN-LAST:event_jButton3ActionPerformed
    
    public  static final BufferedImage scaleImage(int w, int h, BufferedImage img){
        BufferedImage bi;
        bi = new BufferedImage(w, h, BufferedImage.TRANSLUCENT);
        Graphics2D g2d = (Graphics2D) bi.createGraphics();
        g2d.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        g2d.addRenderingHints(new RenderingHints(RenderingHints.KEY_RENDERING, RenderingHints.VALUE_RENDER_QUALITY));
        g2d.drawImage(img, 0, 0, w, h, null);
        g2d.dispose();
        
        return bi;
    }

