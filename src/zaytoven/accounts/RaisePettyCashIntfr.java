    private void validateBeforeSaving(){
        if(txtstaffid.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the staff ID");
            return;
        }
        if(txtstaffname.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the staff Name");
            return;
        }
        if(txtamount.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly input the amount");
            return;
        }
        if(txtreason.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Kindly select the reason");
            return;
        }
        
        
        insertDetails();
    }
    
    private void insertDetails(){
        PreparedStatement pr=null;
        try {
            connect.setAutoCommit(false);
            String requsitionNo=null;
            ResultSet rs=SQLHelper.getResultset(connect, "select 'RQ' || nextval('petty_cash_seq')");
            while(rs.next()){
                requsitionNo=rs.getString(1);
            }
            //insert into petty cash table
            pr=connect.prepareStatement("INSERT INTO petty_cash_requisition(requisition_no, staff_no, amount, reason, username)\n" +
                                                "    VALUES (?, ?, ?::numeric, ?, ?)");
            pr.setString(1, requsitionNo);
            pr.setString(2, txtstaffid.getText());
            pr.setObject(3, txtamount.getText());
            pr.setString(4, txtreason.getText());
            pr.setString(5, userName);
            pr.executeUpdate();
            System.err.println(pr.toString());
            
            
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Insert is Successful");
                resetDetails();
            }
            
            connect.commit();
            connect.setAutoCommit(true);
            
            PettyCashByIDPdf p=new PettyCashByIDPdf();
            p.PettyCashByIDPdf(requsitionNo);
            
        } catch (SQLException ex) {
            try {
                connect.rollback();
            } catch (SQLException ex1) {
                Logger.getLogger(RaisePettyCashIntfr.class.getName()).log(Level.SEVERE, null, ex1);
            }
            Logger.getLogger(RaisePettyCashIntfr.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    
