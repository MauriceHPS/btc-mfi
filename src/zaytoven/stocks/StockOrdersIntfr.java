    private void insertDetails(){
        PreparedStatement pr=null;
        String orderNo=null;
        int levelsRqd=0;
        String sql="INSERT INTO stock_orders( order_id, item_code, quantity_ordered, date_ordered,  supplier_id, ordered_by, price, "
                + "username)"
                + "VALUES (?, ?, ?::int, ?::date, ?, ?, ?::numeric(10, 2), ?)";
            try {
                Statement st=con.createStatement();
                con.setAutoCommit(false);
                ResultSet rs=SQLHelper.getResultset(con, "select 'ORD NO. ' || nextval('order_no_seq')");
                while(rs.next()){
                orderNo=rs.getString(1);
                }
                ResultSet rs1=SQLHelper.getResultset(con, "select count(level) from approvals_setup where category='ORDERS'");
                while(rs1.next()){
                    levelsRqd=rs1.getInt(1);
                }
                for(int i=0;i<jXTable1.getRowCount();i++){
                    if(jXTable1.getValueAt(i, 0)!=null && jXTable1.getValueAt(i, 1)!=null && jXTable1.getValueAt(i, 2)!=null && jXTable1.getValueAt(i, 3)!=null && 
                            jXTable1.getValueAt(i, 4)!=null && jXTable1.getValueAt(i, 5)!=null && jXTable1.getValueAt(i, 6)!=null && jXTable1.getValueAt(i, 7)==Boolean.TRUE){
                        pr=con.prepareStatement(sql);
                        pr.setString(1, orderNo);
                        pr.setObject(2, jXTable1.getValueAt(i, 0));
                        pr.setObject(3, jXTable1.getValueAt(i, 5));
                        pr.setObject(4, "now()");
                        pr.setObject(5, jXTable1.getValueAt(i, 3));
                        pr.setString(6, userName);
                        pr.setObject(7, jXTable1.getValueAt(i, 2));
                        pr.setString(8, userName);
                        pr.executeUpdate();
                    }
                }
            con.commit();
            con.setAutoCommit(true);
            if(pr!=null){
                JOptionPane.showMessageDialog(this, "Insert is Successful");
                OrdersPdf ord=new OrdersPdf();
                ord.OrdersPdf(con, orderNo);
                resetDetails();
                }
            } catch (SQLException ex) {
                Logger.getLogger(StockOrdersIntfr.class.getName()).log(Level.SEVERE, null, ex);
                try {
                    con.rollback();
                } catch (SQLException ex1) {
                    Logger.getLogger(StockOrdersIntfr.class.getName()).log(Level.SEVERE, null, ex1);
                }
            }
        }
