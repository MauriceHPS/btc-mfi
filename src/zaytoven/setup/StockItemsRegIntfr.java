    private void insertDetails(){
    PreparedStatement pr=null;
    String sql=null;
    String itemCode=null;
        try {
            connect.setAutoCommit(false);
            
            
            sql="INSERT INTO stock_items(item_code, item_name, buying_price,  supplier_id, category, min_stock_count, reusable)"
                    + "VALUES (?, INITCAP(?), ?::numeric(10, 2), ?,  ?,  ?::int, ?)";
            pr=connect.prepareStatement(sql);
            
            for(int i=0;i<jXTable1.getRowCount();i++){
                ResultSet rs=SQLHelper.getResultset(connect, "select 'ITM'|| nextval ('item_no_seq')");
            while(rs.next()){
            itemCode=rs.getString(1);
            }
                    pr.setString(1, itemCode);
                if (jXTable1.getModel().getValueAt(i,0) != null && jXTable1.getModel().getValueAt(i,1) != null && jXTable1.getModel().getValueAt(i,2) != null && 
                        jXTable1.getModel().getValueAt(i,3) != null && jXTable1.getModel().getValueAt(i,4) != null && jXTable1.getModel().getValueAt(i,5) != null){
                    pr.setObject(2, jXTable1.getValueAt(i, 0).toString());
                    pr.setObject(3, jXTable1.getValueAt(i, 1).toString());
                    pr.setObject(4, jXTable1.getValueAt(i, 2).toString());
                    pr.setObject(5, jXTable1.getValueAt(i, 3).toString());
                    pr.setObject(6, jXTable1.getValueAt(i, 4).toString());
                    pr.setObject(7, jXTable1.getValueAt(i, 5).toString());
                    pr.executeUpdate();
                }
            }
            connect.commit();
            connect.setAutoCommit(true);
            if(pr!=null){
            JOptionPane.showMessageDialog(this, "Insert is successful");
            resetDetails();
            }
        } catch (SQLException ex) {
            Logger.getLogger(StockItemsRegIntfr.class.getName()).log(Level.SEVERE, null, ex);
        try {
            connect.rollback();
        } catch (SQLException ex1) {
            Logger.getLogger(StockItemsRegIntfr.class.getName()).log(Level.SEVERE, null, ex1);
        }
        }
    }
    
